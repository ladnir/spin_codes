"""Generate the lane-major s22 feedback map f = H mono.

In the fast-circuit basis (state coordinate i <-> monomial masks[i] over the
six step-coordinate bits), one 64-coordinate step of the certified s22 inner is
y_j = x_j + sum_{masks[i] subset j} w_i, mono_i = sum_{j superset masks[i]} x_j,
f = H mono with H = basis * basis^T = map::feedback, and w' = U_e w + f.
The eval and mono networks are hand-structured 8x8 blocks in RouteFast.cpp;
only H is generated here. Writes src/certified22/LaneMajor22.h; --check
verifies that the committed header is current.
"""
from pathlib import Path
import re, sys

root = Path(__file__).resolve().parents[1]
src = (root / 'src/certified22/productionMap.h').read_text()

def arr(name):
    body = re.search(name + r'\{\{(.*?)\}\};', src, re.S).group(1)
    return [int(x, 16) for x in body.replace('ULL', '').replace('U', '').replace('\n', '').split(',') if x.strip()]

feedback = arr('feedback')
assert len(feedback) == 22

lines = []
for i, row in enumerate(feedback):
    terms = [f'mono[{c}]' for c in range(22) if (row >> c) & 1]
    acc, rest = terms[0], terms[1:]
    while rest:
        if len(rest) >= 2:
            acc, rest = f'X::x3({acc},{rest[0]},{rest[1]})', rest[2:]
        else:
            acc, rest = f'X::x2({acc},{rest[0]})', rest[1:]
    lines.append(f'f[{i}]={acc};\n')

text = ''.join([
    '// Generated by tools/generate_lane_major22.py from productionMap.h. Do not edit.\n',
    '// f = H * mono with H = map::feedback; V holds one coordinate for every lane.\n',
    '#pragma once\n',
    'namespace spin::detail::certified22::lanemajor {\n',
    'template<class V,class X>\n',
    'static SPIN_FORCEINLINE void feedbackH(const V* __restrict mono,V* __restrict f) {\n',
    *lines,
    '}\n}\n',
])
dest = root / 'src/certified22/LaneMajor22.h'
if '--check' in sys.argv:
    sys.exit(0 if dest.exists() and dest.read_text() == text else 1)
dest.write_text(text)
print('wrote', dest, 'x2', text.count('X::x2('), 'x3', text.count('X::x3('))
