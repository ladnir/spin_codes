"""Generate/check the parity-only GRS[256,176] FFT transpose wrapper.

The wrapper reuses the previously validated additive FFT helpers. Its output
head doubles as FFT scratch; the only additional explicit array is q[64].
This script only emits text/apply_patch fragments and never writes files.
"""

from __future__ import annotations

import argparse
from pathlib import Path
import random

from generate_cauchy256_outer_fft import (Generator, dot, forward,
                                         interpolation, parity_transpose,
                                         translate, transpose)


def parity_only(values):
    assert len(values) == 80
    q = translate(values[16:])
    q[48:] = [a ^ b for a, b in zip(q[48:], values[:16])]
    output = parity_transpose(q[48:]) + [0]*128
    output[:48] = [a ^ b for a, b in zip(output[:48], q[:48])]
    output[128:] = output[:48]
    output[48:128] = values
    output[:128] = translate(output[:128])
    return output


def generate():
    g = Generator()
    g.lines.extend([
        "// Generated by generate_cauchy256_outer_parity_fft.py; do not edit manually.",
        "// Parity-only transpose of the systematic AES GF256 GRS[256,176] map.",
        "// Input80 are evaluation points 176..255; output176 are source points 0..175.",
        "// Systematic identity contributions are deliberately NOT included.",
        "// Each vector holds four independent 128-bit records; coefficients act per byte.",
        "// Public input/output ranges must be distinct and nonoverlapping; unaligned accepted.",
        "// 1203 GFNI + 2675 XOR. Explicit additional scratch: 4 KiB, plus compiler frames.",
        "// Output head is used as scratch before its final in-place T128 evaluation.",
        "// Ordinary noinline function: never place this aligned array in a coroutine.",
        "#pragma once", '#include "Cauchy256OuterFft.h"',
        "#if defined(_MSC_VER)",
        "#define C256_PARITY_FFT_NOINLINE __declspec(noinline)", "#else",
        "#define C256_PARITY_FFT_NOINLINE __attribute__((noinline))", "#endif",
        "namespace spin::research::char2 {",
        "static C256_PARITY_FFT_NOINLINE void c256OuterParityTransposeFft(const __m512i* input80, __m512i* output176) {",
        "    alignas(64) __m512i q[64];",
    ])
    g.copy("input80", "q", 64, source_first=16)
    g.emit("    c256_outer_fft_detail::translate64(q);")
    g.add("q", "input80", "q", 16, afirst=48, dfirst=48)
    g.emit("    c256_outer_fft_detail::parityTranspose(q+48, output176);")
    g.add("output176", "q", "output176", 48)
    g.copy("output176", "output176", 48, destination_first=128)
    g.copy("input80", "output176", 80, destination_first=48)
    g.emit("    c256_outer_fft_detail::translate128(output176);")
    g.lines.extend(["}", "} // namespace spin::research::char2",
                    "#undef C256_PARITY_FFT_NOINLINE"])
    parts = [g.lines[first:first+200]
             for first in range(0, len(g.lines), 200)]
    parts = [part+[f"// c256-parity-fft-generated-part {i}"]
             for i, part in enumerate(parts)]
    return "\n".join(sum(parts, []))+"\n", parts


def check(header):
    matrix = interpolation(176, range(176, 256))
    checks = 0
    for source in range(80):
        values = [0]*80
        values[source] = 1
        assert parity_only(values) == matrix[source]
        checks += 1
    rng = random.Random(80176)
    for _ in range(16):
        values = [rng.randrange(256) for _ in range(80)]
        systematic = [rng.randrange(256) for _ in range(176)]
        actual = parity_only(values)
        assert actual == [dot([row[j] for row in matrix], values)
                          for j in range(176)]
        assert actual == transpose([0]*176+values)
        assert dot(forward(systematic)[176:], values) == dot(systematic, actual)
        checks += 3
    path = Path(__file__).with_name("Cauchy256OuterParityFft.h")
    if path.exists():
        assert path.read_text() == header, "generated header is incomplete or stale"
    print(f"PASS {checks} exact parity-only basis/dense/full-map/adjoint checks; 1203 GFNI + 2675 XOR; 4 KiB scratch")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--emit", action="store_true")
    parser.add_argument("--patch", type=int)
    args = parser.parse_args()
    header, parts = generate()
    if args.patch is not None:
        i = args.patch
        path = Path(__file__).with_name("Cauchy256OuterParityFft.h").as_posix()
        print("*** Begin Patch")
        print(f"*** {'Add' if i == 0 else 'Update'} File: {path}")
        if i:
            print("@@")
            print(f" // c256-parity-fft-generated-part {i-1}")
        print("\n".join("+"+line for line in parts[i]))
        print("*** End Patch")
    elif args.emit:
        print(header, end="")
    elif args.check:
        check(header)
    else:
        print(f"parts={len(parts)} lines={len(header.splitlines())}")
