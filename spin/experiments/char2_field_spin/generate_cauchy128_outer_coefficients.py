"""Generate/check an evaluation-basis GRS[128,87] outer; no native work.

The source is the first 87 normalized additive-polynomial coefficients.
This is an invertible source reparametrization of the certified outer.
--patch emits an apply_patch addition; this script never writes files.
"""

from __future__ import annotations

import argparse
import difflib
from pathlib import Path
import random
import re

from generate_cauchy256_outer import INV, MUL, interpolation
from generate_cauchy256_outer_fft import (Generator, counts, evaluate, fft_ops,
                                         load, normalized, operation, store)


class CoefficientGenerator(Generator):
    def strided_leaf(self, offset):
        name = f"leaf16_{offset}_strided_transpose"
        self.emit(f"static C256_FFT_NOINLINE void {name}(const unsigned char* source, std::size_t stride, __m512i* p) {{")
        for i in range(16):
            self.emit(f"    auto x{i} = _mm512_loadu_si512(source+{i}*stride);")
        for d, s, c in fft_ops(16, offset, transpose=True):
            self.emit("    "+operation(f"x{d}", f"x{s}", c))
        for i in range(16):
            self.emit("    "+store("p", i, f"x{i}"))
        self.emit("}")
        return name

    def strided_schedule(self, n, offset, start=0):
        if n == 16:
            name = self.strided_leaf(offset)
            return [f"    {name}(source+{start}*stride, stride, p+{start});"]
        half = n//2
        children = (self.strided_schedule(half, offset, start)+
                    self.strided_schedule(half, offset ^ half, start+half))
        coefficient = normalized(half.bit_length()-1, offset)
        name = self.coefficient_stage(half, coefficient, True)
        return children+[f"    {name}(p+{start});"]

    def coefficient_stage(self, half, coefficient, transposed):
        name = f"stage{half}_{coefficient}_{int(transposed)}"
        if name in self.emitted:
            return name
        self.emitted.add(name)
        self.emit(f"static C256_FFT_NOINLINE void {name}(__m512i* p) {{")
        for first in range(0, half, 8):
            self.emit("    {")
            for i in range(8):
                self.emit(f"        auto a{i} = {load('p', first+i)};")
                self.emit(f"        auto b{i} = {load('p', first+half+i)};")
            for i in range(8):
                if transposed:
                    self.emit("        "+operation(f"a{i}", f"b{i}", 1))
                    if coefficient:
                        self.emit("        "+operation(f"b{i}", f"a{i}", coefficient))
                else:
                    if coefficient:
                        self.emit("        "+operation(f"a{i}", f"b{i}", coefficient))
                    self.emit("        "+operation(f"b{i}", f"a{i}", 1))
            for i in range(8):
                self.emit("        "+store("p", first+i, f"a{i}"))
                self.emit("        "+store("p", first+half+i, f"b{i}"))
            self.emit("    }")
        self.emit("}")
        return name

    def coefficient_schedule(self, n, offset, transposed, start=0):
        if n == 16:
            return [f"    {self.leaf(offset, False, transposed)}(p+{start});"]
        half = n//2
        coefficient = normalized(half.bit_length()-1, offset)
        stage = [f"    {self.coefficient_stage(half, coefficient, transposed)}(p+{start});"]
        children = (self.coefficient_schedule(half, offset, transposed, start)+
                    self.coefficient_schedule(half, offset ^ half, transposed, start+half))
        return children+stage if transposed else stage+children


def generate():
    generator = CoefficientGenerator()
    generator.lines.extend([
        "// Generated by generate_cauchy128_outer_coefficients.py; do not edit manually.",
        "// AES GF256 GRS[128,87] in a NONSYSTEMATIC additive-polynomial source basis.",
        "// Source index j is the normalized additive basis polynomial of degree j.",
        "// Each ZMM holds four independent 128-bit records (one per outer row).",
        "// Same outer codeword image as systematic GRS[128,87]; same distance proof.",
        "// This changes source semantics; it is not byte-identical to systematic output.",
        "// Either full 128-point transform: 321 GFNI512, 769 XOR, no lane shuffles.",
        "// In-place hooks allocate no scratch; caller supplies 128 ZMMs (8 KiB).",
        "// Ordinary noinline functions only; never place scratch in coroutine frames.",
        "#pragma once",
        "#include <immintrin.h>",
        "#include <cstddef>",
        "#if defined(_MSC_VER)",
        "#define C256_FFT_NOINLINE __declspec(noinline)",
        "#else",
        "#define C256_FFT_NOINLINE __attribute__((noinline))",
        "#endif",
        "namespace spin::research::char2 {",
        "namespace c128_outer_coefficient_detail {",
    ])
    forward = generator.coefficient_schedule(128, 0, False)
    transpose = generator.coefficient_schedule(128, 0, True)
    strided = generator.strided_schedule(128, 0)
    for name, schedule in (("forward128", forward), ("transpose128", transpose)):
        generator.emit(f"static C256_FFT_NOINLINE void {name}(__m512i* p) {{")
        generator.lines.extend(schedule)
        generator.emit("}")
    generator.emit("static C256_FFT_NOINLINE void transpose128Strided(const unsigned char* source, std::size_t stride, __m512i* p) {")
    generator.lines.extend(strided)
    generator.emit("}")
    generator.emit("} // namespace c128_outer_coefficient_detail")
    generator.emit("// Forward input: coefficients0..86, with coordinates87..127 ZERO.")
    generator.emit("// Forward output: evaluations at byte labels0..127, overwriting all inputs.")
    generator.emit("static C256_FFT_NOINLINE void c128OuterCoefficientForwardInplace(__m512i* values128) {")
    generator.emit("    c128_outer_coefficient_detail::forward128(values128);")
    generator.emit("}")
    generator.emit("// Transpose input: all128 evaluations; result is in coordinates0..86.")
    generator.emit("// Coordinates87..127 are scratch and unspecified. All128 are overwritten.")
    generator.emit("static C256_FFT_NOINLINE void c128OuterCoefficientTransposeInplace(__m512i* values128) {")
    generator.emit("    c128_outer_coefficient_detail::transpose128(values128);")
    generator.emit("}")
    generator.emit("// Fused leaf loads: input coordinate j occupies64 bytes at source+j*strideBytes.")
    generator.emit("// Source and output128 must be disjoint; unaligned input/output are accepted.")
    generator.emit("// Arithmetic unchanged; avoids the initial128 scratch stores and128 leaf reloads.")
    generator.emit("static C256_FFT_NOINLINE void c128OuterCoefficientTransposeStrided(const void* source, std::size_t strideBytes, __m512i* output128) {")
    generator.emit("    c128_outer_coefficient_detail::transpose128Strided(static_cast<const unsigned char*>(source), strideBytes, output128);")
    generator.emit("}")
    generator.emit("// Copying hooks accept disjoint ranges or exactly identical start addresses.")
    generator.emit("static C256_FFT_NOINLINE void c128OuterCoefficientForward(const __m512i* input87, __m512i* output128) {")
    generator.copy("input87", "output128", 87)
    for i in range(87, 128):
        generator.emit("    "+store("output128", i, "_mm512_setzero_si512()"))
    generator.emit("    c128OuterCoefficientForwardInplace(output128);")
    generator.emit("}")
    generator.emit("static C256_FFT_NOINLINE void c128OuterCoefficientTranspose(const __m512i* input128, __m512i* output87) {")
    generator.emit("    alignas(64) __m512i p[128];")
    generator.copy("input128", "p", 128)
    generator.emit("    c128OuterCoefficientTransposeInplace(p);")
    generator.copy("p", "output87", 87)
    generator.emit("}")
    generator.emit("} // namespace spin::research::char2")
    generator.emit("#undef C256_FFT_NOINLINE")
    return "\n".join(generator.lines).replace("C256_FFT_NOINLINE", "C128_COEFF_NOINLINE")+"\n"


def direct_basis(index, point):
    """Direct polynomial evaluation, independent of butterfly decomposition."""
    result = 1
    for bit in range(7):
        if index & (1 << bit):
            numerator = denominator = 1
            for label in range(1 << bit):
                numerator = MUL[numerator][point ^ label]
                denominator = MUL[denominator][(1 << bit) ^ label]
            result = MUL[result][MUL[numerator][INV[denominator]]]
    return result


def dot(a, b):
    result = 0
    for x, y in zip(a, b):
        result ^= MUL[x][y]
    return result


def matrix_rank(matrix):
    a = [list(row) for row in matrix]
    rank = 0
    for column in range(len(a[0])):
        pivot = next((i for i in range(rank, len(a)) if a[i][column]), None)
        if pivot is None:
            continue
        a[rank], a[pivot] = a[pivot], a[rank]
        scale = INV[a[rank][column]]
        a[rank] = [MUL[scale][value] for value in a[rank]]
        for i in range(rank+1, len(a)):
            scale = a[i][column]
            if scale:
                a[i] = [x ^ MUL[scale][y] for x, y in zip(a[i], a[rank])]
        rank += 1
    return rank


def native_program(header):
    """Parse the actual emitted leaf/stage statements into an independent VM."""
    functions = {}
    current = None
    for raw in header.splitlines():
        line = raw.strip()
        match = re.fullmatch(r"static C128_COEFF_NOINLINE void (\w+)\((?:const unsigned char\* source, std::size_t stride, )?__m512i\* p\) \{", line)
        if match:
            current = functions[match[1]] = []
        elif current is not None:
            match = re.fullmatch(r"auto (\w+) = _mm512_loadu_si512\(p\+(\d+)\);", line)
            if match:
                current.append(("load", match[1], int(match[2])))
                continue
            match = re.fullmatch(r"auto (\w+) = _mm512_loadu_si512\(source\+(\d+)\*stride\);", line)
            if match:
                current.append(("source_load", match[1], int(match[2])))
                continue
            match = re.fullmatch(r"(\w+) = _mm512_xor_si512\((\w+), (\w+)\);", line)
            if match:
                current.append(("xor", match[1], match[2], match[3], 1))
                continue
            match = re.fullmatch(r"(\w+) = _mm512_xor_si512\((\w+), _mm512_gf2p8mul_epi8\((\w+), _mm512_set1_epi8\(static_cast<char>\((\d+)\)\)\)\);", line)
            if match:
                current.append(("xor", match[1], match[2], match[3], int(match[4])))
                continue
            match = re.fullmatch(r"_mm512_storeu_si512\(p\+(\d+), (\w+)\);", line)
            if match:
                current.append(("store", int(match[1]), match[2]))
                continue
            match = re.fullmatch(r"(\w+)\(p\+(\d+)\);", line)
            if match:
                current.append(("call", match[1], int(match[2])))
                continue
            match = re.fullmatch(r"(\w+)\(source\+(\d+)\*stride, stride, p\+(\d+)\);", line)
            if match:
                current.append(("source_call", match[1], int(match[2]), int(match[3])))
                continue
            if line in ("{", "}"):
                continue
            # Public wrappers begin after the detail namespace.
            if line.startswith("} // namespace"):
                current = None
                continue
            raise AssertionError(f"Unparsed emitted statement: {line}")
    return functions


def native_evaluate(functions, name, values):
    memory = [0]*128 if name == "transpose128Strided" else list(values)
    def run(function, offset, source_offset=0):
        registers = {}
        for op in functions[function]:
            if op[0] == "load":
                registers[op[1]] = memory[offset+op[2]]
            elif op[0] == "source_load":
                registers[op[1]] = values[source_offset+op[2]]
            elif op[0] == "xor":
                registers[op[1]] = registers[op[2]] ^ MUL[op[4]][registers[op[3]]]
            elif op[0] == "store":
                memory[offset+op[1]] = registers[op[2]]
            elif op[0] == "call":
                run(op[1], offset+op[2])
            else:
                run(op[1], offset+op[3], source_offset+op[2])
    run(name, 0)
    return memory


def check(check_saved=True):
    header = generate()
    program = native_program(header)
    matrix = [[direct_basis(j, point) for j in range(87)] for point in range(128)]
    basis = matrix[:87]
    assert matrix_rank(basis) == 87
    # Every coefficient-basis column equals systematic interpolation of its
    # first87 evaluations. E_coeff = E_systematic * basis, basis invertible.
    parity = interpolation(87, range(87, 128))
    checks = 1
    for point, row in enumerate(parity, 87):
        for j in range(87):
            assert dot(row, [basis[i][j] for i in range(87)]) == matrix[point][j]
            checks += 1
    for j in range(128):
        unit = [int(i == j) for i in range(128)]
        forward = native_evaluate(program, "forward128", unit)
        adjoint = native_evaluate(program, "transpose128", unit)
        assert forward == [direct_basis(j, point) for point in range(128)]
        assert adjoint == [direct_basis(i, j) for i in range(128)]
        assert forward == evaluate(fft_ops(128, 0), unit)
        assert native_evaluate(program, "transpose128Strided", unit) == adjoint
        checks += 4
    rng = random.Random(12887321)
    for _ in range(16):
        source = [rng.randrange(256) for _ in range(87)]
        target = [rng.randrange(256) for _ in range(128)]
        image = native_evaluate(program, "forward128", source+[0]*41)
        adjoint = native_evaluate(program, "transpose128", target)[:87]
        assert image == [dot(row, source) for row in matrix]
        assert adjoint == [dot([row[j] for row in matrix], target) for j in range(87)]
        assert dot(image, target) == dot(source, adjoint)
        assert native_evaluate(program, "transpose128Strided", target)[:87] == adjoint
        checks += 4
    for transposed in (False, True):
        assert dict(counts(fft_ops(128, 0, transpose=transposed))) == {"gfni": 321, "xor": 769}
        checks += 1
    saved = Path(__file__).with_name("Cauchy128OuterCoefficients.h")
    if check_saved:
        assert saved.read_text() == header
        checks += 1
    return checks


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--patch", action="store_true")
    args = parser.parse_args()
    if args.check:
        print(f"{check()} exact checks pass; code-image rank87; 321 GFNI + 769 XOR.")
    elif args.patch:
        check(False)
        path = Path(__file__).with_name("Cauchy128OuterCoefficients.h")
        print("*** Begin Patch")
        if path.exists():
            print("*** Update File: "+path.as_posix())
            difference = list(difflib.unified_diff(path.read_text().splitlines(), generate().splitlines()))
            print("\n".join("@@" if line.startswith("@@") else line for line in difference[2:]))
        else:
            print("*** Add File: "+path.as_posix())
            print("\n".join("+"+line for line in generate().splitlines()))
        print("*** End Patch")
    else:
        print(generate(), end="")


if __name__ == "__main__":
    main()
