"""Generate prefix19 and prefix20 versions of the authenticated t128 circuit."""
from hashlib import sha256
import json
from pathlib import Path
import generate_t128 as base


def main():
    raw = base.SOURCE.read_bytes()
    full = [int(row,16) for row in json.loads(raw)['generator_rows_hex']]
    code = ['// Generated by generate_t128_border.py; fixed prefix maps.',
            f'// Input SHA256: {sha256(raw).hexdigest()}', '#pragma once',
            '#include "../../../src/packet/PacketLargeInner.h"',
            'namespace spin::research::k16codesign::t128border {',
            'using namespace detail::packet::large;',
            'template<unsigned S> struct Map;']
    for s in (19,20):
        rows = full[:s]
        assert not any((a&b).bit_count()&1 for a in rows for b in rows)
        anfs = [base.anf(row) for row in rows]
        coeff = {m:sum(((row>>j)&1)<<i for i,row in enumerate(anfs))
                 for j,m in enumerate(base.MONOMIALS)}
        columns = [sum(((row>>p)&1)<<j for j,row in enumerate(rows)) for p in range(128)]
        monomials = [sum(1<<p for p in range(128) if p&m==m) for m in base.MONOMIALS]
        assert all(base.cse.compose(row,monomials)==literal for row,literal in zip(anfs,rows))
        for p in range(128):
            value = 0
            for m in base.MONOMIALS:
                if p&m==m:value ^= coeff[m]
            assert value==columns[p]
        code += [f'template<> struct Map<{s}> {{',
                 'static constexpr std::uint32_t columns[128]={'+','.join(map(hex,columns))+'};',
                 'template<class Emit> static SPIN_FORCEINLINE void step(const __m128i* state,',
                 'const Block* raw,std::size_t packetBase,Emit& emit,__m128i* moments) {',
                 'alignas(64) __m512i upperHigh[16];']
        generated,cost = base.cse.emit_cse([coeff[m] for m in base.MONOMIALS],
                                          [f'state[{j}]' for j in range(s)],'cs',[f'c{m}' for m in base.MONOMIALS])
        code += [f'// ANF coefficient circuit: {cost} XMM XORs.'] + generated
        code += base.half(1)+base.half(0)+['}']
        code += ['static SPIN_FORCEINLINE void finish128(const __m128i* z,__m128i* out) {']
        generated,finishcost = base.cse.emit_cse(anfs,[f'z[{m}]' for m in base.MONOMIALS],
                                                'fs',[f'f{j}' for j in range(s)])
        code += [f'// Literal A^T feedback: {finishcost} XMM XORs.']+generated
        code += [f'out[{j}]=f{j};' for j in range(s)] + ['}', '};']
        print(f'Validated t128/s{s}: full expansion, feedback, CA=0; coefficient XORs={cost}, feedback XORs={finishcost}.')
    code += ['}']
    (Path(__file__).resolve().parent/'T128BorderMap.h').write_text('\n'.join(code)+'\n',encoding='utf-8',newline='\n')


if __name__=='__main__':main()
