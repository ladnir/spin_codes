"""Generate the fixed t64/s16 minrank monomial packet kernel.

All state/packet indices are compile-time constants. The update and wordpacket
representation remain the retained PacketInnerFast architecture.
"""
from pathlib import Path

HERE=Path(__file__).resolve().parent
MONOMIALS=(0,1,2,4,8,16,32,3,17,33,10,34,12,20,36,24)
HIGH=tuple(m for m in range(16) if m.bit_count()<=2)


def xor(terms):
    if not terms:return '_mm512_setzero_si512()'
    value=terms[0]
    for term in terms[1:]:value=f'_mm512_xor_si512({value},{term})'
    return value


def main():
    assert len(set(MONOMIALS))==16 and 3 in MONOMIALS
    rows=[sum(1<<p for p in range(64) if p&m==m) for m in MONOMIALS]
    assert not any((a&b).bit_count()&1 for a in rows for b in rows)
    columns=[sum((p&m==m)<<j for j,m in enumerate(MONOMIALS)) for p in range(64)]
    d={h:tuple(sum((lane&(m&3)==(m&3))<<j for j,m in enumerate(MONOMIALS) if m>>2==h)
               for lane in range(4)) for h in HIGH}
    for p in range(16):
        for lane in range(4):
            got=0
            for h in HIGH:
                if p&h==h:got^=d[h][lane]
            assert got==columns[4*p+lane]
    code=['// Generated by generate_monomial.py; explicit 16-state minrank monomials.',
          '#pragma once','#include "../../../src/packet/PacketInnerFast.h"',
          'namespace spin::research::k16codesign::monomial {',
          'using namespace detail::packet::fast;',
          'inline constexpr std::uint8_t masks[16]={'+','.join(map(str,MONOMIALS))+'};',
          'inline constexpr std::uint16_t columns[64]={'+','.join(map(hex,columns))+'};',
          'static SPIN_FORCEINLINE void finishMono(const __m128i* z,__m128i* out) {']
    code += [f'out[{j}]=z[{m}];' for j,m in enumerate(MONOMIALS)] + ['}']
    code += ['template<class Emit> static SPIN_FORCEINLINE void stream(const WordPackets16& state,',
             'const Block* raw,std::size_t packetBase,Emit& emit,__m128i* moments) {']
    for j,m in enumerate(MONOMIALS):
        code.append(f'const auto c{m}=_mm512_shuffle_i32x4(state.v[{j//4}],state.v[{j//4}],0x{0x55*(j%4):02x});')
    present=[]
    for h in HIGH:
        terms=[m for m in MONOMIALS if m>>2==h]
        if not terms:continue
        present.append(h)
        base=next((m for m in terms if m%4==0),None)
        code.append(f'auto d{h}='+('_mm512_setzero_si512();' if base is None else f'c{base};'))
        for m in terms:
            if m==base:continue
            mask={1:0xcc,2:0xf0,3:0xc0}[m%4]
            code.append(f'd{h}=_mm512_mask_xor_epi64(d{h},0x{mask:02x},d{h},c{m});')
    for group in (3,2,1,0):
        code += [f'__m512i g{group}0,g{group}1,g{group}2,g{group}3;','{']
        for j in range(3):
            terms=[f'd{h}' for h in present if h%4==j and (h>>2)&group==h>>2]
            code.append(f'const auto b{j}={xor(terms)};')
        code += ['const auto e1=_mm512_xor_si512(b0,b1);',
                 'const auto e2=_mm512_xor_si512(b0,b2);']
        code.append('const auto e3='+xor(['e1','b2']+(['d3'] if 3 in present else []))+';')
        for low in (3,2,1,0):
            h=4*group+low
            expansion=f'e{low}' if low else 'b0'
            code += [f'const auto y{low}=_mm512_xor_si512({expansion},_mm512_loadu_si512(raw+{4*h}));',
                     f'emit(packetBase+{h},y{low});']
        code += [f'g{group}1=_mm512_xor_si512(y1,y3);',f'g{group}2=_mm512_xor_si512(y2,y3);',
                 f'g{group}0=_mm512_ternarylogic_epi64(y0,y2,g{group}1,0x96);',f'g{group}3=y3;','}']
        if group==2:code += [f'const auto cd{j}=_mm512_xor_si512(g2{j},g3{j});' for j in range(4)]
    values={3:'_mm512_ternarylogic_epi64(g03,g13,cd3,0x96)',12:'g30'}
    for j in range(3):
        values[j]=f'_mm512_ternarylogic_epi64(g0{j},g1{j},cd{j},0x96)'
        values[4+j]=f'_mm512_xor_si512(g1{j},g3{j})'
        values[8+j]=f'cd{j}'
    for h in sorted({m>>2 for m in MONOMIALS}):
        degree=max((m&3).bit_count() for m in MONOMIALS if m>>2==h)
        code.append(f'storeLowMoments<{4*h},{degree}>({values[h]},moments);')
    code += ['}','}']
    (HERE/'T64MonomialMap.h').write_text('\n'.join(code)+'\n',encoding='utf-8',newline='\n')
    print('Validated all 64 expansion columns and CA=0 for monomials',MONOMIALS)


if __name__=='__main__':main()
