"""Derive and check the exact certified s22 map's fast-coordinate conversion.

The fixed old map has C=A^T. If A_old=A_mono P and b=P a, the
fast feedback is P C_old = (P P^T) A_mono^T, not A_mono^T.
This generator changes only coordinates, not the certified encoder.
"""
from __future__ import annotations

import argparse
from functools import reduce
from pathlib import Path
import random
import sys

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
sys.path.insert(0, str(ROOT / 'research/workstreams/k16_design'))
import packet_inner_quadratic_extension as certified

MASKS = (0, 1, 2, 3, 4, 8, 16, 32, 5, 9, 17, 33, 6, 10, 18, 34,
         12, 20, 24, 36, 40, 48)
EXPECTED = 'e2467b9d5de8403ccd8263f0f55c73df128a8a2dd4c4cc405bc3a8e057fc3581'


def apply(rows, value):
    return sum(((row & value).bit_count() & 1) << i for i, row in enumerate(rows))


def transpose(rows):
    return tuple(sum(((row >> c) & 1) << r for r, row in enumerate(rows))
                 for c in range(len(rows)))


def multiply(left, right):
    return tuple(reduce(int.__xor__, (right[c] for c in range(len(right)) if row >> c & 1), 0)
                 for row in left)


def inverse(rows):
    n = len(rows)
    work = [row | (1 << (n+i)) for i, row in enumerate(rows)]
    for column in range(n):
        selected = next(i for i in range(column, n) if work[i] >> column & 1)
        work[selected], work[column] = work[column], work[selected]
        for r in range(n):
            if r != column and work[r] >> column & 1:
                work[r] ^= work[column]
    assert tuple(v & ((1 << n)-1) for v in work) == tuple(1 << i for i in range(n))
    return tuple(v >> n for v in work)


def construction():
    old, columns, record = certified.construction(22)
    assert record['map_sha256'] == EXPECTED
    monomials = tuple(sum(int(x & mask == mask) << x for x in range(64)) for mask in MASKS)
    coefficients = []
    for row in old:
        anf = [(row >> x) & 1 for x in range(64)]
        for bit in range(6):
            for x in range(64):
                if x >> bit & 1:
                    anf[x] ^= anf[x ^ (1 << bit)]
        assert not any(anf[x] for x in range(64) if x not in MASKS)
        coeff = sum(anf[mask] << i for i, mask in enumerate(MASKS))
        assert reduce(int.__xor__, (monomials[i] for i in range(22) if coeff >> i & 1), 0) == row
        coefficients.append(coeff)
    basis = transpose(coefficients)
    inverse_basis = inverse(basis)
    identity = tuple(1 << i for i in range(22))
    assert multiply(basis, inverse_basis) == multiply(inverse_basis, basis) == identity
    feedback = multiply(basis, transpose(basis))
    mono_columns = tuple(sum(((row >> x) & 1) << j for j, row in enumerate(monomials))
                         for x in range(64))
    # Check both emission and feedback on every input/state basis vector.
    for j in range(22):
        fast = apply(basis, 1 << j)
        assert reduce(int.__xor__, (monomials[i] for i in range(22) if fast >> i & 1), 0) == old[j]
    for x in range(64):
        assert apply(feedback, mono_columns[x]) == apply(basis, columns[x])
    # C_old A_old=0, which permits feeding back emitted rather than raw words.
    for row in old:
        assert reduce(int.__xor__, (columns[x] for x in range(64) if row >> x & 1), 0) == 0
    # A few arbitrary matrices verify conjugation independently of the C++ setup.
    rng = random.Random(22)
    for _ in range(32):
        matrix = tuple(rng.getrandbits(22) for _ in range(22))
        transformed = multiply(multiply(basis, matrix), inverse_basis)
        for j in range(22):
            assert apply(transformed, apply(basis, 1 << j)) == apply(basis, apply(matrix, 1 << j))
    return old, columns, basis, inverse_basis, feedback


def render():
    old, columns, basis, inverse_basis, feedback = construction()
    text = ['// Generated by generate_maps.py; do not edit by hand.', '#pragma once',
            '#include <array>', '#include <cstdint>', '', 'namespace spin::research::k18cert22::map {',
            f'inline constexpr char sha256[] = "{EXPECTED}";']
    def array(name, kind, values, width):
        text.append(f'inline constexpr std::array<{kind},{len(values)}> {name}{{{{')
        for i in range(0, len(values), 4):
            text.append('    ' + ', '.join(f'0x{v:0{width}x}'+('ULL' if width == 16 else 'U')
                                            for v in values[i:i+4]) + ',')
        text.append('}};')
    array('masks', 'unsigned', MASKS, 2)
    array('oldRows', 'std::uint64_t', old, 16)
    array('oldColumns', 'std::uint32_t', columns, 6)
    array('basis', 'std::uint32_t', basis, 6)
    array('inverseBasis', 'std::uint32_t', inverse_basis, 6)
    array('feedback', 'std::uint32_t', feedback, 6)
    text.append('}')
    return '\n'.join(text) + '\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write', action='store_true', help='regenerate K18Map.h')
    args = parser.parse_args()
    generated = render()
    path = HERE / 'K18Map.h'
    if args.write:
        path.write_text(generated, encoding='utf-8', newline='\n')
    else:
        assert path.read_text(encoding='utf-8') == generated, 'generated K18Map.h differs'
    print('Certified map, basis inverse, feedback transform, and conjugation identities pass.')
