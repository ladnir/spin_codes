#!/usr/bin/env python3
"""Emit the final K20 Turbo endpoint assembly (text only; Lean checks all).

BadSplit22 at R = 512 (q=1, q=2, q>=3), K20 q1/q2 endpoints, the occupation
tail union with n = 256 pairs over the 23 tail pieces (piecewise z, alpha,
rows, bound), and one kernel-checked integer inequality
T^50 * 2^2591 <= 2^(256*50)   (certificate exponent 91249/1622 >= 56.25709 bits at scale 2^256).
No rare-event term is used (see REVISED_SPIN_PROOF_PLAN.md, K20 design).
Output: SpinCodes/Turbo/Generated/K20/Endpoint.lean
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'SpinCodes/Turbo/Generated/K20/Endpoint.lean'
PIECES = json.loads((ROOT / 'SpinCodes/Turbo/Generated/K20Tail/pieces.json').read_text())
NPAIRS, DCUT, GROUPS, R = 256, 209715, 8192, 512
assert PIECES[0]['qlo'] == 3 and PIECES[-1]['qhi'] == GROUPS
assert all(a['qhi'] + 1 == b['qlo'] for a, b in zip(PIECES, PIECES[1:]))
FAMS = sorted({p['f'] for p in PIECES})


def F(f):
    return f'Spin.Turbo.Hi.ProfileFamilyK20Tail{f}22'


def alpha(p):
    return f'((({p["ea"]} : ℕ) : ℝ) / (({p["eb"]} : ℕ) : ℝ))'


def chain(breaks, vals):
    out = [f'  if q ≤ {b} then {v} else' for b, v in zip(breaks, vals)]
    out.append(f'  {vals[-1]}')
    return '\n'.join(out)


PIECE_BREAKS = [p['qhi'] for p in PIECES[:-1]]


def main():
    L = []
    w = L.append
    w('import SpinCodes.Turbo.BadSplit22')
    w('import SpinCodes.Turbo.RoutingFractionalTail22')
    w('import SpinCodes.Turbo.EndpointBits22')
    w('import SpinCodes.Turbo.Generated.K20.Q2Endpoint')
    for p in PIECES:
        w(f'import SpinCodes.Turbo.Generated.K20Tail.TailP{p["piece"]}Agg')
    w('')
    w('/-! Final K20 Turbo endpoint (N = 2097152, cutoff floor(N/10) = 209715).')
    w('Generated by scripts/emit_turbo_k20_endpoint22.py. -/')
    w('noncomputable section')
    w('namespace Spin.Turbo.K20Final')
    w('open Finset Spin.Turbo')
    w('')
    # piecewise by piece (families may repeat across pieces; selecting per piece is simplest)
    w('def zq (q : ℕ) : ℝ :=')
    w(chain(PIECE_BREAKS, [f'{F(p["f"])}.birthSmokeZ22' for p in PIECES]))
    w('')
    w('def Bq (q : ℕ) : Fin 17 → Matrix (Fin 11) (Fin 11) ℝ :=')
    w(chain(PIECE_BREAKS, [f'{F(p["f"])}.selectedRows' for p in PIECES]))
    w('')
    w('def αq (q : ℕ) : ℝ :=')
    w(chain(PIECE_BREAKS, [alpha(p) for p in PIECES]))
    w('')
    w('def A (q : ℕ) : Int :=')
    w(chain(PIECE_BREAKS, [f'{p["ns"]}.aP q' for p in PIECES]))
    w('')
    for f in FAMS:
        w(f'theorem zb_{f} : 0 < {F(f)}.birthSmokeZ22 ∧ {F(f)}.birthSmokeZ22 ≤ 1 := by')
        w(f'  unfold {F(f)}.birthSmokeZ22')
        w(f'  have hn : (0 : ℤ) < {F(f)}.zNum := by decide +kernel')
        w(f'  have hd : {F(f)}.zNum ≤ {F(f)}.zDen := by decide +kernel')
        w(f'  have hd0 : (0 : ℝ) < ({F(f)}.zDen : ℝ) := by exact_mod_cast lt_of_lt_of_le hn hd')
        w(f'  exact ⟨div_pos (by exact_mod_cast hn) hd0, (div_le_one hd0).mpr (by exact_mod_cast hd)⟩')
        w('')
    for i, p in enumerate(PIECES):
        lo, hi = p['qlo'], p['qhi']
        rws = []
        for b in PIECE_BREAKS:
            if b < lo:
                rws.append(f'if_neg (show ¬ q ≤ {b} by omega)')
            else:
                rws.append(f'if_pos (show q ≤ {b} by omega)')
                break
        rw = ', '.join(rws)
        w(f'theorem sel_{i} (q : ℕ) (h1 : {lo} ≤ q) (h2 : q ≤ {hi}) :')
        w(f'    zq q = {F(p["f"])}.birthSmokeZ22 ∧ Bq q = {F(p["f"])}.selectedRows ∧ αq q = {alpha(p)} ∧')
        w(f'      A q = {p["ns"]}.aP q := by')
        w('  refine ⟨?_, ?_, ?_, ?_⟩')
        for nm in ('zq', 'Bq', 'αq', 'A'):
            w(f'  · unfold {nm}; rw [{rw}]')
        w('')
    w('theorem piece_cases (P : ℕ → Prop)')
    for i, p in enumerate(PIECES):
        w(f'    (h{i} : ∀ q, {p["qlo"]} ≤ q → q ≤ {p["qhi"]} → P q)')
    w(f'    : ∀ q ∈ Finset.Ico 3 {GROUPS + 1}, P q := by')
    w('  intro q hq')
    w('  rw [Finset.mem_Ico] at hq')
    for i, p in enumerate(PIECES[:-1]):
        w(f'  by_cases c{i} : q ≤ {p["qhi"]}')
        w(f'  · exact h{i} q (by omega) c{i}')
    w(f'  exact h{len(PIECES) - 1} q (by omega) (by omega)')
    w('')

    def consumer(name, st, body):
        w(f'theorem {name} : ∀ q ∈ Finset.Ico 3 {GROUPS + 1}, {st} := by')
        w('  refine piece_cases _' + ' ?_' * len(PIECES))
        for i, p in enumerate(PIECES):
            w('  · intro q h1 h2')
            w(f'    obtain ⟨hz, hB, hα, hA⟩ := sel_{i} q h1 h2')
            for line in body(i, p):
                w('    ' + line)
        w('')

    consumer('hz0', '0 < zq q', lambda i, p: ['rw [hz]', f'exact (zb_{p["f"]}).1'])
    consumer('hz1', 'zq q ≤ 1', lambda i, p: ['rw [hz]', f'exact (zb_{p["f"]}).2'])
    consumer('ha0', '0 < αq q', lambda i, p: ['rw [hα]', 'positivity'])
    consumer('ha1', 'αq q ≤ 1', lambda i, p: ['rw [hα]', 'exact div_le_one_of_le₀ (by norm_num) (by positivity)'])
    consumer('hs', '∀ j, physicalRowSound22 (Matrix.of (turboSelectedKernel22 j (zq q))) (Bq q j)',
             lambda i, p: ['rw [hz, hB]', f'exact {F(p["f"])}.selectedRows_sound'])
    consumer('hBn', '∀ j a b, 0 ≤ Bq q j a b',
             lambda i, p: ['rw [hB]', f'exact {F(p["f"])}.selectedRows_nonneg'])
    consumer('hterm',
             f'(Nat.choose (({NPAIRS} * 2) * 16) q : ℝ) * ((turboOldUniformFactor22 ^ q / zq q ^ {DCUT}) ^ αq q *\n'
             f'      ∑ k : Fin 11, ((pairedRegionDP22 (Bq q) (αq q) {NPAIRS} q) ^ 64) 0 k) ≤ (A q : ℝ) / 2 ^ 256',
             lambda i, p: ['rw [hz, hB, hα, hA]',
                           f'exact {p["ns"]}.pieceTerm q (Finset.mem_Icc.mpr ⟨h1, h2⟩)'])
    # exact A values from the producer caches (Lean re-derives them in each chunk decide)
    cache = ROOT / '.lake/turbo/k20tail'
    A = {}
    for p in PIECES:
        d = json.loads((cache / f"{p['kind']}{p['piece']}.json").read_text())
        for q, r in d['recs'].items():
            A[int(q)] = r['a']
    assert sorted(A) == list(range(3, GROUPS + 1))
    bounds = list(range(3, GROUPS + 1, 500)) + [GROUPS + 1]
    vals = [sum(A[q] for q in range(a, b)) for a, b in zip(bounds, bounds[1:])]
    total = sum(vals)
    for i, (a, b) in enumerate(zip(bounds, bounds[1:])):
        w(f'theorem chunkS_{i} : ∑ q ∈ Finset.Ico {a} {b}, A q = {vals[i]} := by decide +kernel')
        w('')
    # Two-level assembly: one long rw chain over ~1000 chunks (K = 2^26) times out the
    # elaborator, so join chunks in groups of SUPER, then join the groups.
    SUPER = 50
    def join_sum(name, lo, hi, parts):
        """parts: list of (a, b, lemma) covering [lo, hi) in order."""
        w(f'theorem {name} : ∑ q ∈ Finset.Ico {lo} {hi}, A q = {sum(v for _, _, _, v in parts)} := by')
        rws = []
        for a, b, lem, _ in parts:
            if b != hi:
                rws.append(f'← Finset.sum_Ico_consecutive _ (show {a} ≤ {b} by norm_num) (show {b} ≤ {hi} by norm_num)')
            rws.append(lem)
        w('  rw [' + (',' + chr(10) + '    ').join(rws) + ']')
        w('  all_goals norm_num')
        w('')
    chunks = [(a, b, f'chunkS_{i}', vals[i]) for i, (a, b) in enumerate(zip(bounds, bounds[1:]))]
    supers = []
    for j in range(0, len(chunks), SUPER):
        grp = chunks[j:j + SUPER]
        lo, hi = grp[0][0], grp[-1][1]
        join_sum(f'superS_{j // SUPER}', lo, hi, grp)
        supers.append((lo, hi, f'superS_{j // SUPER}', sum(v for _, _, _, v in grp)))
    join_sum('sumA_eq', 3, GROUPS + 1, supers)
    T = f'({GROUPS} * K20Q1.aSum + K20Q2.b2 + {total})'
    w(f'theorem total_nonneg : (0 : ℤ) ≤ {T} := by decide +kernel')
    w('')
    w(f'theorem total_check : ({T}).toNat ^ 1622 * 2 ^ 91249 ≤ 2 ^ (256 * 1622) := by decide +kernel')
    w('')
    w('theorem k20_endpoint (points : Fin 8 → Field16) (hp : Function.Injective points) :')
    w(f'    (turboSetup22 {R} points).joint.prob')
    w(f'      (fun ω => 1 ≤ (turboSetup22 {R} points).Z {DCUT} ω) ≤ (2 : ℝ) ^ (-(56.25709 : ℝ)) := by')
    w(f'  have hsplit := turboSetup22_bad_prob_split {R} points {DCUT}')
    w('  have h1 := K20Q1.q1_le points hp')
    w('  have h2 := K20Q2.q2_le points hp')
    w(f'  have ht0 := turboOccupationTail22_prob_le_active_union {NPAIRS} points {DCUT} (Finset.Ico 3 {GROUPS + 1})')
    w(f'  have ht1 := turboActiveBadCount22_prob_union_le_paired_dp {NPAIRS} points hp {DCUT}')
    w(f'    (Finset.Ico 3 {GROUPS + 1}) zq αq Bq hz0 hz1 ha0 ha1 hs hBn')
    w('  have ht2 := Finset.sum_le_sum hterm')
    w(f'  have hsum : ∑ q ∈ Finset.Ico 3 {GROUPS + 1}, (A q : ℝ) / 2 ^ 256 =')
    w(f'      ((∑ q ∈ Finset.Ico 3 {GROUPS + 1}, A q : ℤ) : ℝ) / 2 ^ 256 := by')
    w('    rw [← Finset.sum_div]; push_cast; rfl')
    w(f'  have htail : (turboSetup22 {R} points).joint.prob (fun ω =>')
    w(f'      ∃ msg : TurboMessage22 {R}, turboOccupation22 msg ∈ Finset.Ico 3 ({R} * 16 + 1) ∧')
    w(f'        (turboSetup22 {R} points).innerWt ω.2 ((turboSetup22 {R} points).outer ω.1 msg) ≤ {DCUT}) ≤')
    w(f'      ((∑ q ∈ Finset.Ico 3 {GROUPS + 1}, A q : ℤ) : ℝ) / 2 ^ 256 :=')
    w('    ht0.trans (ht1.trans (ht2.trans hsum.le))')
    w('  rw [sumA_eq] at htail')
    w(f'  have hfin := nat_div_two_pow_le_two_rpow_neg {T} 256 91249 1622 (by norm_num)')
    w('    total_nonneg total_check')
    w('  have hmono : (2 : ℝ) ^ (-(((91249 : ℕ) : ℝ) / ((1622 : ℕ) : ℝ))) ≤ (2 : ℝ) ^ (-(56.25709 : ℝ)) :=')
    w('    Real.rpow_le_rpow_of_exponent_le (by norm_num) (by norm_num)')
    w('  refine hsplit.trans ((add_le_add (add_le_add h1 h2) htail).trans (Eq.trans_le ?_ (hfin.trans hmono)))')
    w('  push_cast')
    w('  ring')
    w('')
    w('#print axioms k20_endpoint')
    w('end Spin.Turbo.K20Final')
    OUT.write_text('\n'.join(L) + '\n', encoding='utf-8', newline='\n')
    print(OUT, len(L), 'lines')


if __name__ == '__main__':
    main()
