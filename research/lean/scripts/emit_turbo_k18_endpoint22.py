#!/usr/bin/env python3
"""Emit the final K18 Turbo endpoint assembly module.

Chains BadSplit22 (q=1, q=2, q>=3 split), the K18 q1/q2 endpoint theorems,
the occupation-tail union theorem with piecewise (z, alpha, rows), the
per-family term certificates (famTerm/frTerm/mkTerm), and one kernel-checked
integer inequality T^25 * 2^1456 <= 2^6400 (certificate exponent 84158/1445 >= 58.24083 bits at scale
2^256). Output: SpinCodes/Turbo/Generated/K18/Endpoint.lean
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'SpinCodes/Turbo/Generated/K18/Endpoint.lean'

# (lo, hi, family, kind) ; kind -> (module suffix, sub-namespace, bound fn, term thm)
KINDS = {'Ex': ('ExTerm', 'Ex', 'aFam', 'famTerm'),
         'Fr': ('FrTerm', 'Fr', 'aFr', 'frTerm'),
         'Mk': ('MkTerm', 'Mk', 'aMk', 'mkTerm')}
PIECES = [(3, 5, 1, 'Ex'), (6, 10, 2, 'Ex'), (11, 19, 3, 'Ex'), (20, 34, 4, 'Ex'),
          (35, 51, 5, 'Ex'), (52, 61, 6, 'Ex'), (62, 143, 7, 'Fr'), (144, 157, 8, 'Ex'),
          (158, 185, 9, 'Ex'), (186, 224, 10, 'Ex'), (225, 279, 11, 'Ex'),
          (280, 281, 11, 'Mk'), (282, 344, 12, 'Mk'), (345, 427, 13, 'Mk'),
          (428, 546, 14, 'Mk'), (547, 769, 15, 'Mk'), (770, 1499, 16, 'Mk'),
          (1500, 2048, 17, 'Mk')]
assert PIECES[0][0] == 3 and PIECES[-1][1] == 2048
assert all(a[1] + 1 == b[0] for a, b in zip(PIECES, PIECES[1:]))
FAMS = list(range(1, 18))
FAM_HI = {}
for lo, hi, k, _ in PIECES:
    FAM_HI[k] = max(FAM_HI.get(k, 0), hi)
FAM_BREAKS = [FAM_HI[k] for k in FAMS[:-1]]
PIECE_BREAKS = [p[1] for p in PIECES[:-1]]
ALPHA_BREAKS = [61, 143]
ALL_BREAKS = sorted(set(FAM_BREAKS) | set(PIECE_BREAKS) | set(ALPHA_BREAKS))
assert set(ALPHA_BREAKS) <= set(FAM_BREAKS)


def F(k):
    return f'Spin.Turbo.Hi.ProfileFamilyK18Tail{k}22'


def chain(breaks, vals, ind='  '):
    out = []
    for b, v in zip(breaks, vals):
        out.append(f'{ind}if q ≤ {b} then {v} else')
    out.append(f'{ind}{vals[-1]}')
    return '\n'.join(out)


def alpha(k):
    return '((4 : ℝ) / 5)' if k == 7 else '(1 : ℝ)'


def main():
    L = []
    w = L.append
    w('import SpinCodes.Turbo.BadSplit22')
    w('import SpinCodes.Turbo.RoutingFractionalTail22')
    w('import SpinCodes.Turbo.EndpointBits22')
    w('import SpinCodes.Turbo.Generated.K18.Q2Endpoint')
    for lo, hi, k, kind in PIECES:
        w(f'import SpinCodes.Turbo.Generated.K18Tail.Tail{k}{KINDS[kind][0]}')
    w('')
    w('/-! Final K18 Turbo endpoint (N = 524288, cutoff floor(N/10) = 52428).')
    w('Generated by scripts/emit_turbo_k18_endpoint22.py. -/')
    w('noncomputable section')
    w('namespace Spin.Turbo.K18Final')
    w('open Finset Spin.Turbo')
    w('')
    w('def zq (q : ℕ) : ℝ :=')
    w(chain(FAM_BREAKS, [f'{F(k)}.birthSmokeZ22' for k in FAMS]))
    w('')
    w('def Bq (q : ℕ) : Fin 17 → Matrix (Fin 11) (Fin 11) ℝ :=')
    w(chain(FAM_BREAKS, [f'{F(k)}.selectedRows' for k in FAMS]))
    w('')
    w('def αq (q : ℕ) : ℝ :=')
    w('  if q ≤ 61 then (1 : ℝ) else if q ≤ 143 then ((4 : ℝ) / 5) else (1 : ℝ)')
    w('')
    w('def A (q : ℕ) : Int :=')
    w(chain(PIECE_BREAKS, [f'{F(k)}.{KINDS[kind][1]}.{KINDS[kind][2]} q'
                           for lo, hi, k, kind in PIECES]))
    w('')
    # z bounds per family
    for k in FAMS:
        w(f'theorem zb_{k} : 0 < {F(k)}.birthSmokeZ22 ∧ {F(k)}.birthSmokeZ22 ≤ 1 := by')
        w(f'  unfold {F(k)}.birthSmokeZ22')
        w(f'  have hn : (0 : ℤ) < {F(k)}.zNum := by decide +kernel')
        w(f'  have hd : {F(k)}.zNum ≤ {F(k)}.zDen := by decide +kernel')
        w(f'  have hd0 : (0 : ℝ) < ({F(k)}.zDen : ℝ) := by exact_mod_cast lt_of_lt_of_le hn hd')
        w(f'  exact ⟨div_pos (by exact_mod_cast hn) hd0, (div_le_one hd0).mpr (by exact_mod_cast hd)⟩')
        w('')
    # selectors
    for i, (lo, hi, k, kind) in enumerate(PIECES):
        facts = []
        for b in ALL_BREAKS:
            if b < lo:
                facts.append(f'(by omega : ¬ q ≤ {b})')
            else:
                assert b >= hi
                facts.append(f'(by omega : q ≤ {b})')
        w(f'theorem sel_{i} (q : ℕ) (h1 : {lo} ≤ q) (h2 : q ≤ {hi}) :')
        w(f'    zq q = {F(k)}.birthSmokeZ22 ∧ Bq q = {F(k)}.selectedRows ∧ αq q = {alpha(k)} ∧')
        w(f'      A q = {F(k)}.{KINDS[kind][1]}.{KINDS[kind][2]} q := by')
        def chain_rw(breaks):
            rws = []
            for b in breaks:
                if b < lo:
                    rws.append(f'if_neg (show ¬ q ≤ {b} by omega)')
                else:
                    assert b >= hi
                    rws.append(f'if_pos (show q ≤ {b} by omega)')
                    break
            return ', '.join(rws)
        w('  refine ⟨?_, ?_, ?_, ?_⟩')
        w(f'  · unfold zq; rw [{chain_rw(FAM_BREAKS)}]')
        w(f'  · unfold Bq; rw [{chain_rw(FAM_BREAKS)}]')
        w(f'  · unfold αq; rw [{chain_rw(ALPHA_BREAKS)}]')
        w(f'  · unfold A; rw [{chain_rw(PIECE_BREAKS)}]')
        w('')
    # dispatcher
    w('theorem piece_cases (P : ℕ → Prop)')
    for i, (lo, hi, k, kind) in enumerate(PIECES):
        w(f'    (h{i} : ∀ q, {lo} ≤ q → q ≤ {hi} → P q)')
    w('    : ∀ q ∈ Finset.Ico 3 2049, P q := by')
    w('  intro q hq')
    w('  rw [Finset.mem_Ico] at hq')
    for i, (lo, hi, k, kind) in enumerate(PIECES[:-1]):
        w(f'  by_cases c{i} : q ≤ {hi}')
        w(f'  · exact h{i} q (by omega) c{i}')
    last = len(PIECES) - 1
    w(f'  exact h{last} q (by omega) (by omega)')
    w('')

    def consumer(name, stmt, body):
        w(f'theorem {name} : ∀ q ∈ Finset.Ico 3 2049, {stmt} := by')
        w('  refine piece_cases _ ?_' + ' ?_' * (len(PIECES) - 1))
        for i, (lo, hi, k, kind) in enumerate(PIECES):
            w(f'  · intro q h1 h2')
            w(f'    obtain ⟨hz, hB, hα, hA⟩ := sel_{i} q h1 h2')
            for line in body(i, lo, hi, k, kind):
                w('    ' + line)
        w('')

    consumer('hz0', '0 < zq q', lambda i, lo, hi, k, kind: ['rw [hz]', f'exact (zb_{k}).1'])
    consumer('hz1', 'zq q ≤ 1', lambda i, lo, hi, k, kind: ['rw [hz]', f'exact (zb_{k}).2'])
    consumer('ha0', '0 < αq q', lambda i, lo, hi, k, kind: ['norm_num [hα]'])
    consumer('ha1', 'αq q ≤ 1', lambda i, lo, hi, k, kind: ['norm_num [hα]'])
    consumer('hs', '∀ j, physicalRowSound22 (Matrix.of (turboSelectedKernel22 j (zq q))) (Bq q j)',
             lambda i, lo, hi, k, kind: ['rw [hz, hB]', f'exact {F(k)}.selectedRows_sound'])
    consumer('hBn', '∀ j a b, 0 ≤ Bq q j a b',
             lambda i, lo, hi, k, kind: ['rw [hB]', f'exact {F(k)}.selectedRows_nonneg'])
    consumer('hterm',
             '(Nat.choose ((64 * 2) * 16) q : ℝ) * ((turboOldUniformFactor22 ^ q / zq q ^ 52428) ^ αq q *\n'
             '      ∑ k : Fin 11, ((pairedRegionDP22 (Bq q) (αq q) 64 q) ^ 64) 0 k) ≤ (A q : ℝ) / 2 ^ 256',
             lambda i, lo, hi, k, kind: [
                 'rw [hz, hB, hα, hA]',
                 f'exact {F(k)}.{KINDS[kind][1]}.{KINDS[kind][3]} q (Finset.mem_Icc.mpr ⟨h1, h2⟩)'])

    T = '(2048 * K18Q1.aSum + K18Q2.b2 + ∑ q ∈ Finset.Ico 3 2049, A q)'
    w(f'theorem total_nonneg : (0 : ℤ) ≤ {T} := by decide +kernel')
    w('')
    w(f'theorem total_check : ({T}).toNat ^ 1445 * 2 ^ 84158 ≤ 2 ^ (256 * 1445) := by decide +kernel')
    w('')
    w('theorem k18_endpoint (points : Fin 8 → Field16) (hp : Function.Injective points) :')
    w('    (turboSetup22 128 points).joint.prob')
    w('      (fun ω => 1 ≤ (turboSetup22 128 points).Z 52428 ω) ≤ (2 : ℝ) ^ (-(58.24083 : ℝ)) := by')
    w('  have hsplit := turboSetup22_bad_prob_split 128 points 52428')
    w('  have h1 := K18Q1.q1_le points hp')
    w('  have h2 := K18Q2.q2_le points hp')
    w('  have ht0 := turboOccupationTail22_prob_le_active_union 64 points 52428 (Finset.Ico 3 2049)')
    w('  have ht1 := turboActiveBadCount22_prob_union_le_paired_dp 64 points hp 52428')
    w('    (Finset.Ico 3 2049) zq αq Bq hz0 hz1 ha0 ha1 hs hBn')
    w('  have ht2 := Finset.sum_le_sum hterm')
    w('  have hsum : ∑ q ∈ Finset.Ico 3 2049, (A q : ℝ) / 2 ^ 256 =')
    w('      ((∑ q ∈ Finset.Ico 3 2049, A q : ℤ) : ℝ) / 2 ^ 256 := by')
    w('    rw [← Finset.sum_div]; push_cast; rfl')
    w('  have htail : (turboSetup22 128 points).joint.prob (fun ω =>')
    w('      ∃ msg : TurboMessage22 128, turboOccupation22 msg ∈ Finset.Ico 3 (128 * 16 + 1) ∧')
    w('        (turboSetup22 128 points).innerWt ω.2 ((turboSetup22 128 points).outer ω.1 msg) ≤ 52428) ≤')
    w('      ((∑ q ∈ Finset.Ico 3 2049, A q : ℤ) : ℝ) / 2 ^ 256 :=')
    w('    ht0.trans (ht1.trans (ht2.trans hsum.le))')
    w(f'  have hfin := nat_div_two_pow_le_two_rpow_neg {T} 256 84158 1445 (by norm_num)')
    w('    total_nonneg total_check')
    w('  have hmono : (2 : ℝ) ^ (-(((84158 : ℕ) : ℝ) / ((1445 : ℕ) : ℝ))) ≤ (2 : ℝ) ^ (-(58.24083 : ℝ)) :=')
    w('    Real.rpow_le_rpow_of_exponent_le (by norm_num) (by norm_num)')
    w('  refine hsplit.trans ((add_le_add (add_le_add h1 h2) htail).trans (Eq.trans_le ?_ (hfin.trans hmono)))')
    w('  push_cast')
    w('  ring')
    w('')
    w('#print axioms k18_endpoint')
    w('end Spin.Turbo.K18Final')
    OUT.write_text('\n'.join(L) + '\n', encoding='utf-8', newline='\n')
    print(OUT, len(L), 'lines')


if __name__ == '__main__':
    main()
