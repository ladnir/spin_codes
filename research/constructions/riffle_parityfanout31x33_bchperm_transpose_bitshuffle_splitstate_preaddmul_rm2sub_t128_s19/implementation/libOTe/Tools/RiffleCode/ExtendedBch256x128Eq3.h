		template<typename T>
		static void transposeReference(const T* __restrict word, T* __restrict message)
		{
			for (u64 row = 0; row < dimension; ++row)
			{
				message[row] = T{};
				for (u64 chunk = 0; chunk < 4; ++chunk)
				{
					auto mask = generatorRows[row][chunk];
					while (mask)
					{
						const auto bit = static_cast<u64>(std::countr_zero(mask));
						message[row] ^= word[64 * chunk + bit];
						mask &= mask - 1;
					}
				}
			}
		}
