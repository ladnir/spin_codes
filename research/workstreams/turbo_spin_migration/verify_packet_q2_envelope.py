"""Check the two-position exponent against a certified packet envelope.

Input is generated by verify_packet_spectrum_envelope.py. The outer
envelope has already maximized over both Golay and first-accumulator
weights, so only the two packet fractions remain here.
"""

from __future__ import annotations

import argparse
from fractions import Fraction
import json
import math

from mpmath import iv

from verify_packet_q2_interval import SCHEDULE, inner_upper, inner_witness
from research.workstreams.paper_architecture.certificates.single_sampled_ba_rm2sub.linear_time_audit.verify_outer_interval import (
    HALF, add_upper, as_interval, upper_float,
)


SCHEDULE_CHARGE = upper_float(2*iv.log(iv.mpf(2))/as_interval(SCHEDULE))


def check_pair(first, second, max_depth: int):
    rho1 = (Fraction(first["rho_lo"]), Fraction(first["rho_hi"]))
    rho2 = (Fraction(second["rho_lo"]), Fraction(second["rho_hi"]))
    spectrum = first["upper_nats_per_bit"]+second["upper_nats_per_bit"]
    stack = [(rho1, rho2, 0)]
    largest = -math.inf
    boxes = 0
    while stack:
        r1, r2, depth = stack.pop()
        y1, y2, gamma = inner_witness(sum(r1)*HALF, sum(r2)*HALF)
        value = add_upper(SCHEDULE_CHARGE, spectrum,
                          inner_upper(r1, r2, y1, y2, gamma))
        boxes += 1
        if value < 0:
            largest = max(largest, value)
            continue
        if depth >= max_depth:
            return {"result": "open", "upper": value, "rho1": list(map(str, r1)),
                    "rho2": list(map(str, r2)), "boxes": boxes}
        dim = 0 if r1[1]-r1[0] >= r2[1]-r2[0] else 1
        r = r1 if dim == 0 else r2
        mid = sum(r)*HALF
        for part in ((r[0], mid), (mid, r[1])):
            stack.append((part, r2, depth+1) if dim == 0
                         else (r1, part, depth+1))
    return {"result": "closed", "largest_upper": largest, "boxes": boxes}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("envelope")
    parser.add_argument("--max-depth", type=int, default=20)
    args = parser.parse_args()
    with open(args.envelope, encoding="utf-8") as source:
        data = json.load(source)
    records = data["bands"]
    largest = -math.inf
    checked = boxes = 0
    for i, first in enumerate(records):
        for j in range(i, len(records)):
            result = check_pair(first, records[j], args.max_depth)
            checked += 1
            boxes += result["boxes"]
            if result["result"] != "closed":
                print(json.dumps({"pair": [i, j], "checked": checked,
                                  "total_boxes": boxes, **result}))
                raise SystemExit(1)
            largest = max(largest, result["largest_upper"])
    print(json.dumps({"result": "closed", "pairs": checked, "boxes": boxes,
                      "largest_upper": largest}, sort_keys=True))


if __name__ == "__main__":
    main()
