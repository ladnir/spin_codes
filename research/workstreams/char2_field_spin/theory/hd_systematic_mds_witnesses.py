def replay(precision=256,progress=None):
    with ctx.workprec(precision):
        covered=set();union=arb(0)
        tail=dense_tail_receipt()
        covered.update(range(tail['active_rows_first'],tail['active_rows_last']+1))
        union+=arb(2)**arb(tail['union_log2_upper'])
        for index,(kind,witness) in enumerate(WITNESSES):
            if kind=='paired':
                item=paired(*witness,state=16,threshold=-72,precision=precision,feedthrough='systematic_mds')
            else:
                item=global_bound(*witness,state=16,threshold=-72,precision=precision,feedthrough='systematic_mds')
            intervals=item.get('certified_intervals',[])
            if not intervals:raise ArithmeticError(f'Failed witness {index}')
            for first,last in intervals:covered.update(range(first,last+1))
            union+=arb(2)**arb(item['union_log2_upper'])
            if progress:progress(index+1,len(WITNESSES),len(covered))
        log2=lambda x:x.log()/arb(2).log()
        ideal=log2(union)
        loss=32768*log2((arb(65536)**16-1)/arb(65535)**16)
        final=ideal+loss
        missing=[r for r in range(1,8193) if r not in covered]
        return dict(construction='systematic-global-MDS',state=16,precision=precision,
                    ideal_union_log2_upper=str(ideal),density_loss_bits=str(loss),
                    union_log2_upper=str(final),uncovered_rows=missing,directed=True,
                    whole_code_certificate=not missing and bool(final<-40))


