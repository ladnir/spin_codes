def replay(precision=384,progress=None):
    with ctx.workprec(precision):
        covered=set();union=arb(0)
        tail=dense_tail_receipt()
        covered.update(range(tail['active_rows_first'],tail['active_rows_last']+1))
        union+=arb(2)**arb(tail['union_log2_upper'])
        common=dict(state=16,feedthrough='block4-rank2-fb8',
                    precision=precision,threshold=-72)
        for index,(kind,witness,cutoff) in enumerate(WITNESSES):
            if kind=='paired':item=paired(*witness,cutoff=cutoff,**common)
            elif kind=='global-paired':item=global_bound(*witness,paired=True,**common)
            else:raise ValueError('Unknown pinned witness kind')
            intervals=item.get('certified_intervals',[])
            if not intervals:raise ArithmeticError(f'Failed witness {index}')
            for first,last in intervals:
                if not 1<=first<=last<=8192:raise ArithmeticError('Invalid coverage interval')
                covered.update(range(first,last+1))
            union+=arb(2)**arb(item['union_log2_upper'])
            if progress:progress(index+1,len(WITNESSES),len(covered))
        log2=lambda x:x.log()/arb(2).log()
        ideal=log2(union)
        q=arb(65536)
        loss=32768*log2((q**16-1)/(q-1)**16/((1-1/q)*(1-1/q**2)))
        final=ideal+loss
        missing=[r for r in range(1,8193) if r not in covered]
        return dict(construction='block4-emission-eight-check-rank-two-refresh',
                    field_size=65536,message_length=2**20,code_length=2**21,
                    rate='1/2',forbidden_maximum_weight=838860,state=16,
                    covered_rows=len(covered),precision=precision,
                    ideal_union_log2_upper=str(ideal),density_loss_bits=str(loss),
                    union_log2_upper=str(final),uncovered_rows=missing,directed=True,
                    whole_code_certificate=not missing and bool(final<-40))


