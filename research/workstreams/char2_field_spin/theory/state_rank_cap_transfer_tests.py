"""Exact local checks for the monotone rank-cap cover; no distance claim."""
from fractions import Fraction as F
from itertools import product
import unittest

from diagonal_refresh_rank import rank_potential_bound
from state_rank_cap_transfer import (local_matrix, moment_tail_bound,
                                     monotone_continuation, rank_cap_weights,
                                     rank_tail_envelope, return_flat_factor,
                                     return_minimum_weight)


def gf4_mul(a, b):
    value = 0
    while b:
        if b & 1:
            value ^= a
        b >>= 1
        a <<= 1
        if a & 4:
            a ^= 7
    return value


M4 = tuple(tuple(gf4_mul(a, b) for b in range(4)) for a in range(4))
I4 = (0, 1, 3, 2)


def rank4(rows, columns):
    rows = [list(row) for row in rows]
    rank = 0
    for j in range(columns):
        pivot = next((i for i in range(rank, len(rows)) if rows[i][j]), None)
        if pivot is None:
            continue
        rows[rank], rows[pivot] = rows[pivot], rows[rank]
        rows[rank] = [M4[I4[rows[rank][j]]][x] for x in rows[rank]]
        for i in range(rank+1, len(rows)):
            coefficient = rows[i][j]
            rows[i] = [a ^ M4[coefficient][b] for a, b in zip(rows[i], rows[rank])]
        rank += 1
    return rank


class RankCapTests(unittest.TestCase):
    def test_zero_roots_and_dead_state(self):
        for cap in range(1, 9):
            self.assertEqual(rank_tail_envelope(cap, 0, F(35)), (F(1),)*cap+(F(0),)*(8-cap))
            self.assertEqual(rank_cap_weights(cap, 8, F(35)), (F(0),)*8)

    def test_first_tail_is_the_old_total_potential(self):
        for tau in (F(1), F(7, 2), F(35), F(255)):
            for cap in range(1, 9):
                for roots in range(9):
                    actual = rank_tail_envelope(cap, roots, tau)[0]
                    expected = max(rank_potential_bound(r, roots, tau, 256, 8)
                                   for r in range(1, cap+1))
                    self.assertEqual(actual, expected)

    def test_tail_envelope_is_simultaneous_and_monotone_in_cap(self):
        for tau in (F(2), F(17, 3), F(255)):
            for roots in range(9):
                previous = (F(0),)*8
                for cap in range(1, 9):
                    tails = rank_tail_envelope(cap, roots, tau)
                    masses = rank_cap_weights(cap, roots, tau)
                    self.assertTrue(all(x >= 0 for x in masses))
                    for j in range(8):
                        self.assertEqual(sum(masses[j:]), tails[j])
                        self.assertGreaterEqual(tails[j], previous[j])
                        for rank in range(1, cap+1):
                            self.assertGreaterEqual(tails[j], moment_tail_bound(rank, roots, j+1, tau))
                    previous = tails

    def test_all_gf4_subspaces_and_diagonals(self):
        # Cauchy rows at0,1 and columns at2,3. Five lines plus the full plane
        # exhaust all positive-rank subspaces of GF4^2.
        emission = [[I4[x ^ y] for y in (2, 3)] for x in (0, 1)]
        spaces = [[(1, a)] for a in range(4)] + [[(0, 1)], [(1, 0), (0, 1)]]
        cases = 0
        for basis in spaces:
            rank = len(basis)
            for roots in range(3):
                histogram = [0]*(rank+1)
                for diagonal in product(range(1, 4), repeat=2):
                    equations = []
                    for row in emission[:roots]:
                        equations.append(tuple(M4[M4[row[0]][diagonal[0]]][v[0]]
                                               ^ M4[M4[row[1]][diagonal[1]]][v[1]]
                                               for v in basis))
                    h = rank-rank4(equations, rank)
                    histogram[h] += 1
                for tau in (F(1), F(2), F(3)):
                    for threshold in (1, 2):
                        actual = sum(F(count, 9)*tau**(h-rank)
                                     for h, count in enumerate(histogram) if h >= threshold)
                        upper = moment_tail_bound(rank, roots, threshold, tau, 4, 2)
                        self.assertLessEqual(actual, upper)
                        for cap in range(rank, 3):
                            self.assertLessEqual(actual, rank_tail_envelope(cap, roots, tau, 4, 2)[threshold-1])
                        cases += 1
        self.assertEqual(cases, 108)

    def test_packet_matrices_preserve_the_continuation_cone(self):
        y, tau = F(9, 10), F(7, 2)
        # The cone is generated by the actual-zero ray and the eight upper
        # tails on nonzero caps. Check all generators, not sampled vectors.
        generators = [(F(1),)+(F(0),)*8]
        generators += [tuple(F(int(i >= j)) for i in range(9)) for j in range(1, 9)]
        for weight in range(17):
            matrix = local_matrix(weight, y, tau)
            self.assertTrue(all(value >= 0 for row in matrix for value in row))
            for values in generators:
                output = monotone_continuation(matrix, values)
                self.assertTrue(all(output[r] <= output[r+1] for r in range(1, 8)))

    def test_scalar_cap8_nonreturn_matches_old_one_packet_total(self):
        from superregular_return_screen import local_matrix as old_matrix
        y, tau = F(9, 10), F(7)
        for weight in (0, 1, 2, 8, 9, 16):
            new = local_matrix(weight, y, tau)
            old = old_matrix(weight, y, tau)
            self.assertEqual(new[0][0], old[0][0])
            self.assertEqual(sum(new[0][1:]), old[0][1])
            if weight:
                self.assertEqual(new[8][0], return_flat_factor(weight, tau, 8)
                                 *y**return_minimum_weight(weight)/tau**8)
                self.assertLessEqual(new[8][0], old[1][0])
            else:
                self.assertEqual(new[8][0], 0)
            self.assertEqual(sum(new[8][1:]), old[1][1])

    def test_symmetric_block_identity_and_return_minima(self):
        import state_capacity_reference as scalar
        self.assertEqual(tuple(return_minimum_weight(w) for w in range(1, 17)),
                         (9, 9, 9, 9, 8, 6, 4, 2)+(1,)*8)
        for phase in range(4):
            a, c = scalar.matrices(phase, True)
            gram = tuple(tuple(scalar.xor_sum(scalar.mul(x, y) for x, y in zip(row, column))
                               for column in zip(*c)) for row in a)
            for i in range(16):
                for j in range(16):
                    if i//8 == j//8:
                        self.assertEqual(gram[i][j], int(i == j))
                    else:
                        difference = scalar.LABELS[phase][i] ^ scalar.LABELS[phase][j]
                        self.assertEqual(gram[i][j], scalar.power(difference, 254))
            # Exact all nonzero two-input ratios, one same-half and one
            # split-half placement. The general bound follows from Cauchy.
            for inputs in ((0, 1), (0, 8)):
                minimum = 16
                for ratio in range(1, 256):
                    values = (1, ratio)
                    output = []
                    for j in range(16):
                        injected = scalar.xor_sum(scalar.mul(gram[j][i], x)
                                                  for i, x in zip(inputs, values))
                        direct = values[inputs.index(j)] if j in inputs else 0
                        output.append(direct ^ scalar.mul(2, injected))
                    minimum = min(minimum, sum(bool(x) for x in output))
                self.assertGreaterEqual(minimum, return_minimum_weight(2))
                self.assertEqual(minimum, 9 if inputs == (0, 1) else 15)

    def test_a_birth_retains_its_small_rank_cap(self):
        y, tau = F(9, 10), F(7)
        birth, empty = local_matrix(1, y, tau), local_matrix(0, y, tau)
        self.assertEqual(birth[0][1], y)
        self.assertTrue(all(x == 0 for x in birth[0][2:]))
        # At rank cap1, every surviving empty packet keeps cap1. Its total
        # is strictly below the rank-agnostic cap8 empty-packet envelope.
        self.assertTrue(all(x == 0 for x in empty[1][2:]))
        self.assertLess(sum(empty[1]), sum(empty[8]))

    def test_reject_nonmonotone_continuation(self):
        with self.assertRaises(ValueError):
            monotone_continuation(local_matrix(1, F(1, 2), F(7)), (0, 1, 0, 0, 0, 0, 0, 0, 0))

    def test_float_cache_does_not_contaminate_exact_evaluation(self):
        moment_tail_bound(7, 2, 3, 11.0)
        rank_tail_envelope(7, 2, 11.0)
        self.assertIsInstance(moment_tail_bound(7, 2, 3, F(11)), F)
        self.assertTrue(all(isinstance(x, F) for x in rank_tail_envelope(7, 2, F(11))))


if __name__ == '__main__':
    unittest.main()
