def check_witness(task):
    index,witness,cutoff,precision=task
    item=receipt(*witness,precision=precision,cutoff=cutoff,threshold=-72)
    if not item["certified_intervals"]:
        raise ArithmeticError(f"Failed witness {index}")
    return index,item


def replay(precision=384,workers=1,progress=None):
    if precision<128 or not 1<=workers<=16:
        raise ValueError("Use precision >=128 and 1..16 worker processes")
    tasks=[(i,w,c,precision) for i,(w,c) in enumerate(WITNESSES)]
    pool=ProcessPoolExecutor(max_workers=workers,mp_context=get_context("spawn")) if workers>1 else None
    try:
        results=pool.map(check_witness,tasks,chunksize=1) if pool else map(check_witness,tasks)
        with ctx.workprec(precision):
            covered=set();union=arb(0)
            tail=dense_tail_receipt()
            covered.update(range(tail["active_rows_first"],tail["active_rows_last"]+1))
            union+=arb(2)**arb(tail["union_log2_upper"])
            for index,item in results:
                if not item["directed"] or item["precision"]!=precision:
                    raise ArithmeticError("Invalid precision or arithmetic")
                if item["feedback_schedule"]!=[4,4,4,8]:
                    raise ArithmeticError("Wrong feedback schedule")
                for first,last in item["certified_intervals"]:
                    if not 1<=first<=last<=8192:
                        raise ArithmeticError("Invalid coverage interval")
                    covered.update(range(first,last+1))
                union+=arb(2)**arb(item["union_log2_upper"])
                if progress:progress(index+1,len(WITNESSES),len(covered))
            log2=lambda x:x.log()/arb(2).log()
            ideal=log2(union);q=arb(65536)
            loss=32768*log2(q/(q-1)*(q**16-1)/(q-1)**16)
            final=ideal+loss
            missing=[r for r in range(1,8193) if r not in covered]
            return dict(construction="global-emission-feedback-4-4-4-8",
                        field_size=65536,message_length=2**20,code_length=2**21,
                        rate="1/2",forbidden_maximum_weight=838860,state=16,
                        feedback_schedule=[4,4,4,8],covered_rows=len(covered),
                        precision=precision,workers=workers,
                        ideal_union_log2_upper=str(ideal),density_loss_bits=str(loss),
                        union_log2_upper=str(final),uncovered_rows=missing,directed=True,
                        whole_code_certificate=not missing and bool(final<-40))
    finally:
        if pool:pool.shutdown()


