"""Bounded GF(16) checks for lookahead rank charges; no files or timings.

These exact two-dimensional quotient fixtures check the proposed local lemma,
not a K20 certificate. Input forms are fixed before both steps' coefficients.
"""

from collections import defaultdict
from fractions import Fraction as F
from itertools import product
from random import Random

from test_local_algebra import COEFFICIENTS, require
from test_rank_transfer import scale, support, zero_span, reduce_form
from coupled_rank_transfer import lookahead_charge, lookahead_transition_terms


def step(inputs, state, coefficients):
    outputs = tuple(x ^ scale(a, q) for x, a, q in zip(inputs, coefficients, state))
    return outputs, (state[1] ^ outputs[0], state[0] ^ outputs[1])


def rotate(mask):
    return ((mask & 1) << 1) | ((mask >> 1) & 1)


def charge(state, output, following):
    return (state & ~(output & following)).bit_count()


def lookahead(state, output, following, after_following):
    eligible = state & output & following
    return sum(bool(eligible & (1 << j))
               and not ((following | after_following) & rotate(1 << j))
               for j in range(2))


def retained_branches(inputs, state, observations, history):
    """Enumerate every retained zero-span branch in a two-dimensional space.

    Rank two kills a required nonzero form. Rank-one spans must be generated
    by one of the observed nonzero zero-equation forms. Thus this covers all
    retained branches without enumerating every proposed four-mask tuple.
    """
    required = [v for v in inputs + state if v] + list(history)
    require(bool(required), "fixtures must require a nonzero form")
    flat = tuple(v for vector in observations for v in vector)
    candidates = {(0, 0)} | {zero_span((v,)) for v in flat if v}
    result = {}
    for basis in candidates:
        if any(reduce_form(v, basis) == 0 for v in required):
            continue
        masks = tuple(support(tuple(reduce_form(v, basis) for v in vector))
                      for vector in observations)
        zeros = [v for v in flat if reduce_form(v, basis) == 0]
        actual_basis = zero_span(zeros)
        require(actual_basis == basis, "candidate span is not generated by its zero equations")
        potential = F(1, 2**sum(bool(row) for row in basis))
        require(masks not in result, "duplicate zero-equation span")
        result[masks] = potential
    return result


def check_two_step():
    forms = (0, 1, 16, 17, 2, 33)
    rng = Random(20261020)
    fixtures = [tuple(rng.choice(forms) for _ in range(6)) for _ in range(384)]
    # Explicit localized-state fixtures: X0=(0,f0), X1=(0,f1), Q0=(f0,0).
    fixtures += [(0, f0, 0, f1, f0, 0) for f0, f1 in product(forms[1:], repeat=2)]
    count = branches = lagged = 0
    for fixture in fixtures:
        x0, x1, q0 = fixture[:2], fixture[2:4], fixture[4:]
        if not any(fixture):
            continue
        h0 = support(q0)
        for history in ((), (33,)):
            expected = defaultdict(F)
            for a0a1 in product(COEFFICIENTS, repeat=4):
                y0, q1 = step(x0, q0, a0a1[:2])
                y1, q2 = step(x1, q1, a0a1[2:])
                for masks, potential in retained_branches(x0 + x1, q0, (y0, q1, y1, q2), history).items():
                    expected[masks] += potential / 16
            for (j0, h1, j1, h2), value in expected.items():
                extra = lookahead(h0, j0, h1, h2)
                require(extra == lookahead_charge(2, h0, j0, h1, h2), "lookahead kernel count")
                total = charge(h0, j0, h1) + charge(h1, j1, h2) + extra
                require(value <= F(1, 2**total),
                        ("lookahead domination", fixture, history, (j0, h1, j1, h2), value, total))
                branches += 1
                lagged += extra > 0
            count += 1
    require(lagged > 0, "no improved branch was checked")
    return count, branches, lagged


def check_localization_runs():
    forms = (1, 16, 17, 2, 33)
    cases = 0
    for length in range(1, 5):
        for inputs in product(forms, repeat=length):
            expected = F(0)
            for coefficients in product(COEFFICIENTS, repeat=length - 1):
                zeros = [inputs[t + 1] ^ scale(a, inputs[t])
                         for t, a in enumerate(coefficients)]
                basis = zero_span(zeros)
                if all(reduce_form(v, basis) for v in inputs):
                    expected += F(1, 2**sum(bool(row) for row in basis)) / 2**(length - 1)
            require(expected <= F(1, 2**(length - 1)), "localization run charge")
            cases += 1
    return cases


def main():
    fixtures, branches, lagged = check_two_step()
    runs = check_localization_runs()
    # The ordinary singleton-localization edge has no fresh charge; lookahead
    # recovers exactly one when localization is required on the next step.
    require(lookahead_transition_terms(2, 2, 1, 1, 1) == ((2, 1, 1),),
            "localized augmented edge")
    # No lookahead charge if the next rotated position is allowed to stay live.
    require(lookahead_transition_terms(2, 2, 1, 1, 3) == ((2, 0, 1),),
            "lookahead must not charge an absent future zero")
    print(f"two-step fixtures={fixtures}; retained mask branches={branches}; lag-charged branches={lagged}")
    print(f"localization-run fixtures={runs}; lengths=1..4")
    print("PASS: bounded exact lookahead-rank checks; no full-code certificate")


if __name__ == "__main__":
    main()
