"""Two-type epoch operators from shape-resolved inner bounds.

Each type has an exact packet-weight law on {0,1,2,3,4}. B[j1,j2] averages
over j1 selected groups of the first type and j2 of the second type in
distinct, uniformly assigned epoch slots. Selected groups that draw weight
zero remain selected for placement; zero only contributes no active packet
to the shape-resolved inner operator.

For j1+j2 <= model.cut, convolve the two laws exactly into the multiplicities
of weights 1..4, then average model.shapes[k][counts], k=sum(counts). Uniform
placement of the type labels makes active slot locations and lane-weight
assignments exchangeable conditional on counts. Thus the shape operator's
within-epoch averaging is the required one; no extra factorial is inserted.

Above the selected-group cutoff, retain only the number k of active packets.
Its law is the convolution of Bin(j1,1-law1[0]) and Bin(j2,1-law2[0]). For
k<=cut use the entrywise maximum U_k of the shape operators; above cut use
model.fallback[k]. This is a deliberately looser universal bound, not an
assertion that the two nonzero packet laws coincide. In particular, equal
laws agree with exact homogeneous thinning through the cutoff, and with
universal-U_k thinning above it.

All probabilities are exact rationals. Only their positive matrix averages
use Arb; each result is rounded outward before it enters typed placement.
No new inner census is generated by this module.
"""
from collections import defaultdict
from fractions import Fraction as Q
from math import comb

from flint import arb, arb_mat, ctx

from typed_placement import upper_matrix


def _law(values):
    values=tuple(Q(x) for x in values)
    if len(values)!=5 or any(x<0 for x in values) or sum(values)!=1:
        raise ValueError('five nonnegative exact packet probabilities summing to one required')
    return values


def _probability(value):
    return arb(value.numerator)/value.denominator


def _advance_shapes(previous, law):
    result=defaultdict(Q)
    for counts,mass in previous.items():
        if law[0]:
            result[counts]+=mass*law[0]
        for weight in range(1,5):
            if law[weight]:
                updated=list(counts)
                updated[weight-1]+=1
                result[tuple(updated)]+=mass*law[weight]
    assert sum(result.values())==1
    return dict(result)


def _advance_active(previous, zero):
    result=[Q(0)]*(len(previous)+1)
    for active,mass in enumerate(previous):
        result[active]+=mass*zero
        result[active+1]+=mass*(1-zero)
    assert sum(result)==1
    return tuple(result)


def _matrix(value, size):
    if value.nrows()!=size or value.ncols()!=size:
        raise ValueError('inner operators must have equal square dimensions')
    converted=arb_mat([[arb(value[i,j]) for j in range(size)] for i in range(size)])
    if any(not converted[i,j].is_finite() or not converted[i,j]>=0
           for i in range(size) for j in range(size)):
        raise ValueError('nonnegative finite inner operators required')
    return upper_matrix(converted)


def _model_operators(model, maximum):
    cut=model.cut
    if not isinstance(cut,int) or cut<0:
        raise ValueError('nonnegative integer shape cutoff required')
    try:
        empty=model.shapes[0][(0,0,0,0)]
    except KeyError as error:
        raise ValueError('missing zero-packet shape operator') from error
    size=empty.nrows()
    if size<1 or empty.ncols()!=size:
        raise ValueError('nonempty square inner operators required')
    shapes={}
    universal=[]
    for active in range(maximum+1):
        if active<=cut:
            if active not in model.shapes:
                raise ValueError(f'missing shape operators at active count {active}')
            entries=model.shapes[active]
            if (len(entries)!=comb(active+3,3)
                    or any(len(counts)!=4 or any(not isinstance(x,int) or x<0 for x in counts)
                           or sum(counts)!=active for counts in entries)):
                raise ValueError(f'incomplete multiplicity shapes at active count {active}')
            shapes[active]={counts:_matrix(value,size) for counts,value in entries.items()}
            values=list(shapes[active].values())
            universal.append(arb_mat([[max(value[i,j] for value in values)
                                       for j in range(size)] for i in range(size)]))
        else:
            try:
                fallback=model.fallback[active]
            except (KeyError,IndexError) as error:
                raise ValueError(f'missing universal fallback at active count {active}') from error
            universal.append(_matrix(fallback,size))
    return size,shapes,universal


def build_typed_operators(model, law1, law2, *, max_counts=(32,32), slots=32):
    """Return {(j1,j2): B_j1,j2} for the required local type counts.

    Counts satisfy 0<=ji<=max_counts[i] and j1+j2<=slots. model supplies cut,
    shapes, fallback, and optionally precision. Its high-occupancy fallback
    must bound every nonzero packet-weight pattern; this premise cannot be
    established from the matrices alone.
    """
    law1,law2=_law(law1),_law(law2)
    max_counts=tuple(max_counts)
    if (not isinstance(slots,int) or slots<1 or len(max_counts)!=2
            or any(not isinstance(x,int) or x<0 for x in max_counts)):
        raise ValueError('positive slot count and two nonnegative maximum counts required')
    maximum=min(slots,sum(max_counts))
    precision=getattr(model,'precision',ctx.prec)
    if not isinstance(precision,int) or precision<32:
        raise ValueError('precision must be an integer of at least 32 bits')
    previous_precision=ctx.prec
    ctx.prec=precision
    try:
        size,shapes,universal=_model_operators(model,maximum)
        shape_laws={(0,0):{(0,0,0,0):Q(1)}}
        active_laws={(0,0):(Q(1),)}
        result={}
        for j1 in range(min(max_counts[0],slots)+1):
            for j2 in range(min(max_counts[1],slots-j1)+1):
                selected=j1+j2
                key=j1,j2
                if selected:
                    previous=(j1-1,j2) if j1 else (0,j2-1)
                    law=law1 if j1 else law2
                    active_laws[key]=_advance_active(active_laws[previous],law[0])
                    if selected<=model.cut:
                        shape_laws[key]=_advance_shapes(shape_laws[previous],law)
                value=arb_mat(size,size)
                if selected<=model.cut:
                    for counts,mass in shape_laws[key].items():
                        value+=_probability(mass)*shapes[sum(counts)][counts]
                else:
                    # Even a low active count uses the universal U_k here:
                    # this branch intentionally discards the type's shape law.
                    for active,mass in enumerate(active_laws[key]):
                        if mass:
                            value+=_probability(mass)*universal[active]
                result[key]=upper_matrix(value)
        return result
    finally:
        ctx.prec=previous_precision
