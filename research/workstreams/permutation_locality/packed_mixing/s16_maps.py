"""Explicit research candidates for a 128-bit epoch and 16-bit inner state.

A is the subcode generated by the first sixteen independent rows of the
retained NO_CONSTANT_MAP expansion. C is sampled afresh from distinct
weight-five columns, or is an explicit extended-BCH parity-check map.
Neither choice is a truncation of a running 19-bit state machine.
"""
import argparse
from collections import Counter
from itertools import combinations
import json
from math import comb
from pathlib import Path
import random

HERE = Path(__file__).resolve().parent
RESEARCH = HERE.parents[2]


def binary_rank(words):
    pivots = {}
    for value in words:
        while value:
            p = value.bit_length()-1
            if p not in pivots:
                pivots[p] = value
                break
            value ^= pivots[p]
    return len(pivots)


def gf_multiply(a, b):
    value = 0
    while b:
        if b & 1:
            value ^= a
        b >>= 1
        a <<= 1
        if a & 128:
            a ^= 0x83  # x^7+x+1, checked by the complete nonzero cycle below.
    return value


def images_from_rows(rows):
    images = [0] * (1 << len(rows))
    for state in range(1, len(images)):
        bit = state & -state
        images[state] = images[state ^ bit] ^ rows[bit.bit_length()-1]
    return images


def dual_spectrum(spectrum, length, dimension):
    result = []
    for degree in range(length+1):
        total = sum(count * sum((-1)**j*comb(weight, j)*comb(length-weight, degree-j)
                    for j in range(max(0, degree-length+weight), min(degree, weight)+1))
                    for weight, count in spectrum.items())
        quotient, remainder = divmod(total, 1 << dimension)
        if remainder or quotient < 0:
            raise ArithmeticError('invalid exact MacWilliams count')
        result.append(quotient)
    if sum(result) != 1 << (length-dimension):
        raise ArithmeticError('incorrect kernel cardinality')
    return result


def candidate(feedback='weight5', seed=0):
    original = json.loads((RESEARCH/'workstreams/inner_design/NO_CONSTANT_MAP.json').read_text())
    rows = [int(word, 16) for word in original['generator_rows_hex'][:16]]
    if len(rows) != 16 or binary_rank(rows) != 16:
        raise ArithmeticError('candidate expansion needs sixteen independent rows')
    images = images_from_rows(rows)
    if feedback == 'weight5':
        pool = [sum(1 << j for j in support) for support in combinations(range(16), 5)]
        columns = random.Random(seed).sample(pool, 128)
        description = '128 distinct weight-five columns on 16 coordinates; Python Random(seed).sample in lexicographic support order'
    elif feedback == 'bch16':
        cycle, value = set(), 1
        for _ in range(127):
            cycle.add(value)
            value = gf_multiply(value, 2)
        if value != 1 or cycle != set(range(1, 128)):
            raise ArithmeticError('GF128 modulus did not generate the complete nonzero cycle')
        columns = []
        for x in range(128):
            square = gf_multiply(x, x)
            cube = gf_multiply(square, x)
            fifth = gf_multiply(gf_multiply(square, square), x)
            columns.append(1 | (x << 1) | (cube << 8) | ((fifth & 1) << 15))
        description = 'column x = (1, binary(x), binary(x^3), low_bit(x^5)); x in GF128, modulus x^7+x+1'
    else:
        raise ValueError('unknown feedback candidate')
    if binary_rank(columns) != 16 or len(set(columns)) != 128 or not all(columns):
        raise ArithmeticError('candidate feedback must be full rank, nonzero and distinct')
    feedback_rows = [sum(((column >> j) & 1) << i for i, column in enumerate(columns)) for j in range(16)]
    a_spectrum = dict(sorted(Counter(image.bit_count() for image in images).items()))
    ct_spectrum = dict(sorted(Counter(image.bit_count() for image in images_from_rows(feedback_rows)).items()))
    kernel = dual_spectrum(ct_spectrum, 128, 16)
    record = dict(schema='s16-explicit-map-candidate-1', t=128, s=16,
        expansion='first sixteen generator rows of NO_CONSTANT_MAP.json, as a new declared injective subcode',
        expansion_rows_hex=list(map(hex, rows)), expansion_spectrum=a_spectrum,
        feedback=feedback, feedback_seed=seed if feedback == 'weight5' else None,
        feedback_definition=description, feedback_columns=columns,
        feedback_transpose_spectrum=ct_spectrum, feedback_kernel_spectrum=list(map(str, kernel)),
        expansion_rank=16, feedback_rank=16, minimum_expansion_weight=min(w for w in a_spectrum if w),
        minimum_feedback_kernel_weight=next(w for w in range(1, 129) if kernel[w]),
        packet_ranks=[binary_rank(columns[i:i+4]) for i in range(0, 128, 4)],
        whole_code_certificate=False)
    return images, columns, record


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--feedback', choices=('weight5', 'bch16'), default='weight5')
    parser.add_argument('--seed', type=int, default=0)
    parser.add_argument('--output', type=Path)
    args = parser.parse_args()
    _, _, record = candidate(args.feedback, args.seed)
    if args.output:
        if args.output.exists():
            parser.error('fresh output path required')
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(json.dumps(record, indent=2)+'\n')
    print(json.dumps({key: value for key, value in record.items() if key not in
        ('feedback_kernel_spectrum', 'feedback_columns', 'expansion_rows_hex')}, indent=2))


if __name__ == '__main__':
    main()
