"""Exact one-packet birth census for fixed S16 feedback-basis candidates.

Keep A fixed and replace C by B*C for an explicitly authenticated B in
GL(16,2). This preserves ker(C), the code generated by rows of C, and all
column-subset ranks, but changes A*C*x. It is a new inner construction,
not a coordinate rewrite of the complete encoder and not a certificate.

The exact moment is the rational polynomial sum_w count[w]*z**w/480.
Its evaluation at z=exp(-27/100) uses outward Arb arithmetic. Search seeds
identify deterministic candidates, not a cryptographic setup distribution.
"""
import argparse
from collections import Counter
from fractions import Fraction as Q
from functools import cmp_to_key
import hashlib
import json
from pathlib import Path
import random
import sys

from flint import arb, ctx

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
import s16_maps


def fingerprint(value):
    return hashlib.sha256(json.dumps(value, sort_keys=True,
        separators=(',', ':')).encode()).hexdigest()


def apply_rows(rows, value):
    """Output bit i is parity(rows[i] & value)."""
    return sum(((row & value).bit_count() & 1) << i
               for i, row in enumerate(rows))


def invert(rows):
    """Exact Gauss-Jordan inverse, rejecting malformed/singular matrices."""
    rows = tuple(rows)
    bits = len(rows)
    if not 1 <= bits <= 16 or any(type(row) is not int or not 0 <= row < 1 << bits
                                 for row in rows):
        raise ValueError('one bounded integer row mask per coordinate required')
    left, right = list(rows), [1 << i for i in range(bits)]
    for col in range(bits):
        pivot = next((i for i in range(col, bits) if left[i] >> col & 1), None)
        if pivot is None:
            raise ValueError('invertible feedback basis required')
        left[col], left[pivot] = left[pivot], left[col]
        right[col], right[pivot] = right[pivot], right[col]
        for i in range(bits):
            if i != col and left[i] >> col & 1:
                left[i] ^= left[col]
                right[i] ^= right[col]
    if left != [1 << i for i in range(bits)] or any(
            apply_rows(right, apply_rows(rows, 1 << i)) != 1 << i
            or apply_rows(rows, apply_rows(right, 1 << i)) != 1 << i
            for i in range(bits)):
        raise ArithmeticError('inverse composition failed')
    return tuple(right)


def seeded_basis(seed, bits=16):
    """Rejection-sample full-rank row masks; explicit rows identify the map."""
    if type(seed) is not int or type(bits) is not int or not 1 <= bits <= 16:
        raise ValueError('integer seed and dimension in 1..16 required')
    rng = random.Random(seed)
    attempts = 0
    while True:
        attempts += 1
        rows = tuple(rng.getrandbits(bits) for _ in range(bits))
        if s16_maps.binary_rank(rows) == bits:
            invert(rows)
            return rows, attempts


def feedback_rows(columns, bits):
    return tuple(sum(((column >> j) & 1) << i for i, column in enumerate(columns))
                 for j in range(bits))


def transform(columns, basis):
    """Authenticate C'=B*C and its exact inverse on every input basis bit."""
    inverse = invert(basis)
    bits = len(basis)
    columns = tuple(columns)
    if not columns or any(type(c) is not int or not 0 <= c < 1 << bits for c in columns):
        raise ValueError('bounded feedback columns required')
    changed = tuple(apply_rows(basis, c) for c in columns)
    if tuple(apply_rows(inverse, c) for c in changed) != columns:
        raise ArithmeticError('feedback column recovery failed')
    old_rows, new_rows = feedback_rows(columns, bits), feedback_rows(changed, bits)
    for index, row in enumerate(basis):
        expected = 0
        for j in range(bits):
            if row >> j & 1:
                expected ^= old_rows[j]
        if expected != new_rows[index]:
            raise ArithmeticError('feedback row-operation identity failed')
    if s16_maps.binary_rank(columns) != s16_maps.binary_rank(changed):
        raise ArithmeticError('feedback rank changed')
    # The invertible row operation proves equality for all subsets; check
    # the local packet ranks too because they are consumed by the proof.
    if any(s16_maps.binary_rank(columns[i:i+4]) != s16_maps.binary_rank(changed[i:i+4])
           for i in range(0, len(columns), 4)):
        raise ArithmeticError('packet rank changed')
    return changed, inverse


def birth_census(images, columns):
    """Enumerate all packet positions and nonzero four-bit labels exactly."""
    if not columns or len(columns) % 4 or any(not 0 <= c < len(images) for c in columns):
        raise ValueError('complete packet geometry and indexed map images required')
    histogram, joint = Counter(), Counter()
    for start in range(0, len(columns), 4):
        for label in range(1, 16):
            state = 0
            for j in range(4):
                if label >> j & 1:
                    state ^= columns[start+j]
            weight = images[state].bit_count()
            histogram[weight] += 1
            joint[(label.bit_count(), weight)] += 1
    denominator = 15 * (len(columns)//4)
    if sum(histogram.values()) != denominator or sum(joint.values()) != denominator:
        raise ArithmeticError('one-packet census mass mismatch')
    return dict(sorted(histogram.items())), dict(sorted(joint.items())), denominator


def exact_moment(histogram, denominator, z):
    """Evaluate the exact census polynomial at a rational argument."""
    z = Q(z)
    if denominator != sum(histogram.values()) or denominator <= 0 or not 0 < z <= 1:
        raise ValueError('normalized census and rational z in (0,1] required')
    return sum((Q(n, denominator)*z**w for w, n in histogram.items()), Q(0))


def tilted_moment(histogram, denominator, tilt=Q(27, 100)):
    """Enclose the exact transcendental moment; no floating census counts."""
    tilt = Q(tilt)
    if tilt <= 0 or denominator != sum(histogram.values()) or denominator <= 0:
        raise ValueError('positive tilt and normalized census required')
    z = (-arb(tilt.numerator)/tilt.denominator).exp()
    value = sum((int(n)*z**int(w) for w, n in histogram.items()), arb(0))/denominator
    if not value.is_finite() or not value > 0:
        raise ArithmeticError('positive finite moment enclosure required')
    return value


def evaluate(feedback, feedback_seed=0, seeds=tuple(range(16)), precision=192):
    if type(precision) is not int or precision < 128:
        raise ValueError('at least 128-bit outward precision required')
    seeds = tuple(seeds)
    if not seeds or any(type(seed) is not int for seed in seeds) or len(set(seeds)) != len(seeds):
        raise ValueError('distinct nonempty integer candidate seeds required')
    images, original, map_record = s16_maps.candidate(feedback, feedback_seed)
    previous_precision = ctx.prec
    ctx.prec = precision
    try:
        bases = [('identity', None, tuple(1 << j for j in range(16)), 0)]
        bases += [(f'seed-{seed}', seed, *seeded_basis(seed)) for seed in seeds]
        candidates, moments = [], {}
        for name, seed, basis, attempts in bases:
            columns, inverse = transform(original, basis)
            histogram, joint, denominator = birth_census(images, columns)
            moment = tilted_moment(histogram, denominator)
            moments[name] = moment
            candidates.append(dict(name=name, seed=seed, rejection_attempts=attempts,
                basis_rows_hex=[hex(v) for v in basis], inverse_rows_hex=[hex(v) for v in inverse],
                basis_sha256=fingerprint(list(basis)), feedback_columns=list(columns),
                feedback_columns_sha256=fingerprint(list(columns)),
                kernel_and_row_code_preserved=True,
                histogram=[dict(weight=w, count=n) for w, n in histogram.items()],
                joint_input_birth_histogram=[dict(input_weight=u, birth_weight=w, count=n)
                                             for (u, w), n in joint.items()],
                denominator=denominator, bad48_count=histogram.get(48, 0),
                bad48_fraction=str(Q(histogram.get(48, 0), denominator)),
                below48_count=sum(n for w, n in histogram.items() if w < 48),
                zero_birth_count=histogram.get(0, 0),
                moment_at_exp_minus_27_over_100=str(moment),
                moment_lower=list(map(int, moment.lower().man_exp())),
                moment_upper=list(map(int, moment.upper().man_exp()))))

        def moment_order(a, b):
            if a['histogram'] == b['histogram']:
                return (a['name'] > b['name']) - (a['name'] < b['name'])
            x, y = moments[a['name']], moments[b['name']]
            if x < y:
                return -1
            if y < x:
                return 1
            raise ArithmeticError('candidate moment intervals overlap; increase precision')

        moment_rank = sorted(candidates, key=cmp_to_key(moment_order))
        ranks = {row['name']: i for i, row in enumerate(moment_rank)}
        bad48_rank = sorted(candidates, key=lambda row: (row['bad48_count'], ranks[row['name']]))
        return dict(schema='s16-fixed-feedback-basis-one-packet-search-1',
            scope='Only exact j=1 birth counts; no other occupancy, interval or whole-code certificate.',
            whole_code_certificate=False, feedback=feedback,
            feedback_seed=map_record['feedback_seed'], bits=16, width=128,
            input_law='uniform one of 32 packet positions and uniform nonzero four-bit label',
            expansion_rows_hex=map_record['expansion_rows_hex'],
            expansion_spectrum=map_record['expansion_spectrum'],
            original_feedback_columns=list(original),
            original_feedback_columns_sha256=fingerprint(list(original)),
            original_feedback_kernel_minimum=map_record['minimum_feedback_kernel_weight'],
            basis_convention='output bit i = parity(basis_rows[i] & old_state); C_new = B*C_old; A unchanged',
            basis_generation='Python Random(seed).getrandbits(16), sixteen rows per trial, reject singular trials',
            kernel_preservation='Checked B inverse and C_new=B*C_old on all 128 input basis vectors; hence ker(C_new)=ker(C_old) and their row codes coincide.',
            tilt='27/100', precision=precision,
            moment_definition='sum_w histogram[w]*exp(-27*w/100)/480',
            rank_by_bad48_then_moment=[row['name'] for row in bad48_rank],
            rank_by_moment=[row['name'] for row in moment_rank], candidates=candidates)
    finally:
        ctx.prec = previous_precision


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--feedback', choices=('weight5', 'bch16', 'both'), default='both')
    parser.add_argument('--feedback-seed', type=int, default=0)
    parser.add_argument('--seeds', type=int, nargs='+', default=list(range(16)))
    parser.add_argument('--precision', type=int, default=192)
    args = parser.parse_args()
    choices = ('weight5', 'bch16') if args.feedback == 'both' else (args.feedback,)
    print(json.dumps([evaluate(feedback, args.feedback_seed, args.seeds, args.precision)
                      for feedback in choices], indent=2))


if __name__ == '__main__':
    main()
