"""Generate exact wide feedback from the11 packet high moments.

The first seven syndrome coordinates remain wide.  Only quadratic moments
cross into128-bit words for the retained32-XOR circuit; the resulting four
ZMM syndrome vectors feed the unchanged composed GFNI state update directly.
"""
import argparse
from pathlib import Path
import sys

import inner_packet_codegen as maps
import inner_stream_codegen as stream


def verified_maps():
    rows, columns, _, _, _, digest, _ = maps.retained.prepare()
    mr = [maps.anf(row) for row in rows]
    co = {m: sum(((r >> j) & 1) << i for i, r in enumerate(mr))
          for j, m in enumerate(maps.MONOMIALS)}
    basis = [1 << j for j in range(7)] + [co[m] for m in (3, 5, 9, 17, 33, 6, 10, 34, 12)]
    forms = [maps.compose(p, mr) for p in basis]
    physical = [maps.compose(p, rows) for p in basis]
    monomials = {m: sum(1 << p for p in range(64) if p & m == m) for m in maps.MONOMIALS}
    high = {h: tuple(sum(1 << (4*p+lane) for p in range(16) if p & h == h)
                     for lane in range(4)) for h in stream.HIGH}
    def shuffle(a, b, imm):
        return (a[imm & 3], a[(imm >> 2) & 3],
                b[(imm >> 4) & 3], b[(imm >> 6) & 3])
    def xor(*values):
        return tuple(__import__('functools').reduce(int.__xor__, lane, 0)
                     for lane in zip(*values))
    def mask_xor(a, b, mask):
        if any(((mask >> (2*i)) & 3) not in (0, 3) for i in range(4)):
            raise ArithmeticError('partial128-bit payload mask')
        return tuple(a[i] ^ (b[i] if mask >> (2*i) & 1 else 0) for i in range(4))
    def transpose4(a, b, c, d):
        ab0, ab1 = shuffle(a, b, 0x44), shuffle(a, b, 0xee)
        cd0, cd1 = shuffle(c, d, 0x44), shuffle(c, d, 0xee)
        return (shuffle(ab0, cd0, 0x88), shuffle(ab0, cd0, 0xdd),
                shuffle(ab1, cd1, 0x88), shuffle(ab1, cd1, 0xdd))
    z = {}
    h = high[0]
    l0 = mask_xor(h, shuffle(h, h, 0xf5), 0x33)
    low0 = mask_xor(l0, shuffle(l0, l0, 0xee), 0x0f)
    for m, value in zip((0, 1, 2, 3), low0):
        z[m] = value
    a, b, c, d = transpose4(*(high[h] for h in (1, 2, 4, 8)))
    odd, upper = xor(b, d), xor(c, d)
    total = xor(a, c, odd)
    for i, h in enumerate((1, 2, 4, 8)):
        z[4*h], z[4*h+1], z[4*h+2] = total[i], odd[i], upper[i]
    quadratic = xor(*transpose4(*(high[h] for h in (3, 5, 6, 9))))
    for m, value in zip((12, 20, 24, 36), quadratic):
        z[m] = value
    pair = xor(shuffle(high[10], high[12], 0x44), shuffle(high[10], high[12], 0xee))
    both = xor(pair, shuffle(pair, pair, 0xb1))
    z[40], z[48] = both[0], both[2]
    if z != monomials:
        raise ArithmeticError('wide folding changed a complete moment linear form')
    scalar = [maps.compose(form, [z[m] for m in maps.MONOMIALS]) for form in forms]
    feedback0 = list(low0)
    replacement = shuffle(total, total, 0x00)
    for lane in range(4):
        if 0xc0 >> (2*lane) & 1:
            feedback0[lane] = replacement[lane]
    feedback1 = list(shuffle(total, total, 0x39))
    feedback1[3] = scalar[7]
    got = feedback0 + feedback1 + scalar[8:]
    if got != physical:
        raise ArithmeticError('wide feedback assembly changed physical feedback')
    code, cost = maps.emit_cse(forms[7:], [f'z{m}' for m in maps.MONOMIALS],
                               'fs', [f'f{j}' for j in range(7, 16)])
    if cost != 32:
        raise ArithmeticError('quadratic feedback circuit cost changed')
    return code, physical, digest


def generate():
    finish, physical, digest = verified_maps()
    source = [f'''// Generated by further_feedback_codegen.py; exact retained t64/s16 feedback.
// Authenticated selected map SHA256: {digest}
#pragma once
#include "further_mapWide.h"
namespace spin::research::packet_inner {{
#if defined(__AVX512VBMI__) || (defined(SPIN_PACKET_ENABLE_VBMI) && SPIN_PACKET_ENABLE_VBMI)
namespace further_feedback_detail {{
using Words=composed_detail::WordPackets16;
namespace gf=spin::research::gfni_r4;

struct Four {{ __m512i a,b,c,d; }};
static SPIN_FORCEINLINE Four transpose4(__m512i a,__m512i b,__m512i c,__m512i d){{
const auto ab0=_mm512_shuffle_i32x4(a,b,0x44);
const auto ab1=_mm512_shuffle_i32x4(a,b,0xee);
const auto cd0=_mm512_shuffle_i32x4(c,d,0x44);
const auto cd1=_mm512_shuffle_i32x4(c,d,0xee);
return {{_mm512_shuffle_i32x4(ab0,cd0,0x88),_mm512_shuffle_i32x4(ab0,cd0,0xdd),
_mm512_shuffle_i32x4(ab1,cd1,0x88),_mm512_shuffle_i32x4(ab1,cd1,0xdd)}};
}}
static SPIN_FORCEINLINE __m512i totals4(__m512i a,__m512i b,__m512i c,__m512i d){{
const auto t=transpose4(a,b,c,d);
return _mm512_ternarylogic_epi64(t.a,t.b,_mm512_xor_si512(t.c,t.d),0x96);
}}

// Eleven high moments only; the other five high slots remain unread.
static SPIN_FORCEINLINE void finishHigh(const __m512i* high,Words& feedback){{
const auto l0=_mm512_mask_xor_epi64(high[0],0x33,high[0],
_mm512_shuffle_i32x4(high[0],high[0],0xf5));
const auto low=_mm512_mask_xor_epi64(l0,0x0f,l0,_mm512_shuffle_i32x4(l0,l0,0xee));
const auto z3=_mm512_extracti32x4_epi32(low,3);

const auto middle=transpose4(high[1],high[2],high[4],high[8]);
const auto odd=_mm512_xor_si512(middle.b,middle.d);
const auto upper=_mm512_xor_si512(middle.c,middle.d);
const auto total=_mm512_ternarylogic_epi64(middle.a,middle.c,odd,0x96);
const auto z5=_mm512_castsi512_si128(odd);
const auto z9=_mm512_extracti32x4_epi32(odd,1);
const auto z17=_mm512_extracti32x4_epi32(odd,2);
const auto z33=_mm512_extracti32x4_epi32(odd,3);
const auto z6=_mm512_castsi512_si128(upper);
const auto z10=_mm512_extracti32x4_epi32(upper,1);
const auto z18=_mm512_extracti32x4_epi32(upper,2);
const auto z34=_mm512_extracti32x4_epi32(upper,3);

const auto quadratic=totals4(high[3],high[5],high[6],high[9]);
const auto z12=_mm512_castsi512_si128(quadratic);
const auto z20=_mm512_extracti32x4_epi32(quadratic,1);
const auto z24=_mm512_extracti32x4_epi32(quadratic,2);
const auto z36=_mm512_extracti32x4_epi32(quadratic,3);
const auto pair0=_mm512_shuffle_i32x4(high[10],high[12],0x44);
const auto pair1=_mm512_shuffle_i32x4(high[10],high[12],0xee);
const auto pair=_mm512_xor_si512(pair0,pair1);
const auto both=_mm512_xor_si512(pair,_mm512_shuffle_i32x4(pair,pair,0xb1));
const auto z40=_mm512_castsi512_si128(both);
const auto z48=_mm512_extracti32x4_epi32(both,2);
''']
    source.extend(finish)
    source.append('''// One masked shuffle replaces a broadcast plus blend for coordinate3.
feedback.v[0]=_mm512_mask_shuffle_i64x2(low,0xc0,total,total,0x00);
feedback.v[1]=_mm512_inserti32x4(_mm512_shuffle_i32x4(total,total,0x39),f7,3);
feedback.v[2]=gf::join(f8,f9,f10,f11);
feedback.v[3]=gf::join(f12,f13,f14,f15);
}

static SPIN_FORCEINLINE void highFromPackets(const __m512i* packets,__m512i* high){
using feedback_detail::firstStage;
const auto a=firstStage<0>(packets),b=firstStage<4>(packets);
const auto c=firstStage<8>(packets),d=firstStage<12>(packets);
const auto z4=_mm512_xor_si512(b.z0,d.z0);
const auto z8=_mm512_xor_si512(c.z0,d.z0);
high[0]=_mm512_ternarylogic_epi64(a.z0,c.z0,z4,0x96);
high[4]=z4;high[8]=z8;high[12]=d.z0;
const auto z5=_mm512_xor_si512(b.z1,d.z1);
const auto z9=_mm512_xor_si512(c.z1,d.z1);
high[1]=_mm512_ternarylogic_epi64(a.z1,c.z1,z5,0x96);
high[5]=z5;high[9]=z9;
const auto z6=_mm512_xor_si512(b.z2,d.z2);
const auto z10=_mm512_xor_si512(c.z2,d.z2);
high[2]=_mm512_ternarylogic_epi64(a.z2,c.z2,z6,0x96);
high[6]=z6;high[10]=z10;
high[3]=_mm512_ternarylogic_epi64(a.z3,b.z3,_mm512_xor_si512(c.z3,d.z3),0x96);
}

// The retained composed update, with its four word-packet feedback vectors
// already assembled. No syndrome words are extracted or joined here.
static SPIN_FORCEINLINE void update(const gf::Packed<16>& before,
const ComposedWordRow16& row,const Words& feedback,Words& words){
const auto m00=_mm512_set1_epi64(row.data[0]);
const auto m01=_mm512_set1_epi64(row.data[1]);
const auto m10=_mm512_set1_epi64(row.data[2]);
const auto m11=_mm512_set1_epi64(row.data[3]);
const auto lo0=_mm512_xor_si512(_mm512_gf2p8affine_epi64_epi8(m00,before.v[0],0),
_mm512_gf2p8affine_epi64_epi8(m01,before.v[2],0));
const auto hi0=_mm512_xor_si512(_mm512_gf2p8affine_epi64_epi8(m00,before.v[1],0),
_mm512_gf2p8affine_epi64_epi8(m01,before.v[3],0));
const auto lo1=_mm512_xor_si512(_mm512_gf2p8affine_epi64_epi8(m10,before.v[0],0),
_mm512_gf2p8affine_epi64_epi8(m11,before.v[2],0));
const auto hi1=_mm512_xor_si512(_mm512_gf2p8affine_epi64_epi8(m10,before.v[1],0),
_mm512_gf2p8affine_epi64_epi8(m11,before.v[3],0));
words.v[0]=_mm512_xor_si512(_mm512_permutex2var_epi8(lo0,vbmi_state_detail::unpackIndex<0>(),hi0),feedback.v[0]);
words.v[1]=_mm512_xor_si512(_mm512_permutex2var_epi8(lo0,vbmi_state_detail::unpackIndex<4>(),hi0),feedback.v[1]);
words.v[2]=_mm512_xor_si512(_mm512_permutex2var_epi8(lo1,vbmi_state_detail::unpackIndex<0>(),hi1),feedback.v[2]);
words.v[3]=_mm512_xor_si512(_mm512_permutex2var_epi8(lo1,vbmi_state_detail::unpackIndex<4>(),hi1),feedback.v[3]);
}

template<class Emit> static SPIN_FORCEINLINE void reverse(
const spin::detail::kernel::block* input,std::size_t n,const ComposedWordRow16* rows,Emit& emit){
alignas(64) __m512i packets[16],high[16];
gf::Packed<16> before;
Words state,feedback;
for(std::size_t epoch=n/64;epoch-- >0;){
const auto* raw=input+64*epoch;
const bool first=epoch+1==n/64;
if(first){
packet_kernel_detail::loadPackets(raw,packets,std::make_index_sequence<16>{});
for(unsigned h=16;h-- >0;)emit(16*epoch+h,packets[h]);
}else{
if(epoch){composed_detail::packWordGroup<0>(state,before);composed_detail::packWordGroup<1>(state,before);}
further_map_detail::streamHigh<false,false>(state,raw,16*epoch,emit,high);
}
if(!epoch)break;
if(first)highFromPackets(packets,high);
finishHigh(high,feedback);
if(first)state=feedback;
else update(before,rows[epoch],feedback,state);
}
}
} // further_feedback_detail
#endif

template<class Emit> static SPIN_FORCEINLINE void transposeInnerFurtherFeedback(
const spin::detail::kernel::block* input,std::size_t n,
PreparedComposedUpdates16::Rows updates,Emit&& emit){
static_assert(packetInnerVbmiCompiled || sizeof(Emit)==0,
"wide feedback requires a VBMI-enabled translation unit");
if(n%64 || updates.size()!=n/64)
throw std::invalid_argument("wide feedback length and update count disagree");
if(!n)return;
if(!input)throw std::invalid_argument("wide feedback input is null");
#if defined(__AVX512VBMI__) || (defined(SPIN_PACKET_ENABLE_VBMI) && SPIN_PACKET_ENABLE_VBMI)
further_feedback_detail::reverse(input,n,updates.data(),emit);
#endif
}

template<ComposedRecipe Recipe,class Emit>
static SPIN_FORCEINLINE void transposeInnerFurtherFeedbackRecipe(
const spin::detail::kernel::block* input,std::size_t n,
PreparedComposedUpdates16::Rows updates,Emit&& emit){
if constexpr(Recipe==ComposedRecipe::Packet)
transposeInnerComposedWide<Recipe>(input,n,updates,emit);
else{static_assert(Recipe==ComposedRecipe::Stream);
transposeInnerFurtherFeedback(input,n,updates,emit);}
}

[[nodiscard]] inline bool furtherFeedbackSelfCheck(){
#if defined(__AVX512VBMI__) || (defined(SPIN_PACKET_ENABLE_VBMI) && SPIN_PACKET_ENABLE_VBMI)
alignas(64) std::uint64_t input[128]{};
alignas(64) __m512i packets[16],high[16];
further_feedback_detail::Words actual;
''')
    source.append('static constexpr std::array<std::uint64_t,16> feedbackRows={'
                  + ','.join(f'0x{row:016x}ULL' for row in physical) + '};')
    source.append('''for(unsigned coordinate=0;coordinate<64;++coordinate){
for(unsigned bit=0;bit<128;++bit){
const auto value=std::uint64_t(1)<<(bit&63);
input[2*coordinate+(bit>>6)]=value;
for(unsigned h=0;h<16;++h)packets[h]=_mm512_load_si512(input+8*h);
further_feedback_detail::highFromPackets(packets,high);
further_feedback_detail::finishHigh(high,actual);
alignas(64) std::uint64_t got[8];
for(unsigned g=0;g<4;++g){
_mm512_store_si512(got,actual.v[g]);
for(unsigned lane=0;lane<4;++lane){
const auto expected=(feedbackRows[4*g+lane]>>coordinate&1)?value:0;
if(got[2*lane]!=(bit<64?expected:0) || got[2*lane+1]!=(bit>=64?expected:0))return false;
}
}
input[2*coordinate+(bit>>6)]=0;
}
}
return true;
#else
return false;
#endif
}
} // spin::research::packet_inner
''')
    return '\n'.join(source)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path)
    parser.add_argument('--probe-output', type=Path)
    parser.add_argument('--verify-only', action='store_true')
    args = parser.parse_args()
    header = generate()
    if args.output and not args.verify_only:
        args.output.write_text(header, encoding='utf-8', newline='\n')
    elif not args.verify_only:
        print(header)
    if args.probe_output and not args.verify_only:
        original = Path(__file__).with_name('creative_probe.cpp').read_text()
        substitutions = (
            ('#include "InnerComposed.h"', '#include "further_feedbackWide.h"'),
            ('ip::transposeInnerComposedWide<Mode == 3 ? ip::ComposedRecipe::Packet : ip::ComposedRecipe::Stream>',
             'ip::transposeInnerFurtherFeedbackRecipe<Mode == 3 ? ip::ComposedRecipe::Packet : ip::ComposedRecipe::Stream>'),
            ('if(!ip::composedStateSelfCheck())',
             'if(!ip::composedStateSelfCheck() || !ip::furtherMapWideSelfCheck() || !ip::furtherFeedbackSelfCheck())'),
        )
        for before, after in substitutions:
            if original.count(before) != 1:
                raise ArithmeticError('retained creative probe interface changed: '+before)
            original = original.replace(before, after)
        args.probe_output.write_text(
            '// Generated isolated harness: creative mode4/6 uses wide emission and feedback.\n'+original,
            encoding='utf-8', newline='\n')
    print('Verified all22 wide-fold moment forms, all16 physical feedback forms, '
          'and retained32-XOR quadratic finisher.', file=sys.stderr)


if __name__ == '__main__':
    main()
