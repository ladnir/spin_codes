"""Generate exact wide-state packet emission without a word-state round trip.

State stays in four coordinate-major ZMM vectors.  Broadcasts needed for
lane-masked packet coefficients are shared with the quadratic ANF circuit.
The existing authenticated stream evaluator and feedback maps are unchanged.
"""
import argparse
from pathlib import Path
import sys

import inner_packet_codegen as maps
import inner_stream_codegen as stream


def coefficients_code(coefficients):
    lines, symbols, broadcasts = [], {}, set()

    def broadcast(j):
        if j not in broadcasts:
            lines.append(f'const auto b{j}=_mm512_shuffle_i32x4('
                         f'state.v[{j//4}],state.v[{j//4}],0x{(j%4)*0x55:02x});')
            symbols[f'b{j}'] = (1 << j,)*4
            broadcasts.add(j)
        return f'b{j}'

    # These are the five nonconstant-lane ANF packet coefficients.  Emit each
    # as soon as its low-coordinate broadcasts are ready, so b0..b6 die early.
    specs = ((0, 0, ((1, 0b1010), (2, 0b1100), (7, 0b1000))),
             (1, 3, ((8, 0b1010), (12, 0b1100))),
             (2, 4, ((9, 0b1010), (13, 0b1100))),
             (4, 5, ((10, 0b0110), (12, 0b1100))),
             (8, 6, ((11, 0b1010), (14, 0b1100))))
    masked_count = 0
    for h, base, terms in specs:
        name = broadcast(base)
        # Read all coefficients before assigning d: native mask operations
        # act on two64-bit pieces of each128-bit payload element together.
        for j, _ in terms:
            broadcast(j)
        lines.append(f'auto d{h}={name};')
        form = list(symbols[name])
        for j, lane_mask in terms:
            mask = sum(3 << (2*lane) for lane in range(4) if lane_mask >> lane & 1)
            lines.append(f'd{h}=_mm512_mask_xor_epi64(d{h},0x{mask:02x},d{h},b{j});')
            for lane in range(4):
                if lane_mask >> lane & 1:
                    form[lane] ^= 1 << j
            masked_count += 1
        symbols[f'd{h}'] = tuple(form)
    broadcast(15)
    forms = [coefficients[4*h] for h in (3, 5, 6, 9, 10, 12)]
    code, count = maps.emit_cse(forms, [f'b{j}' for j in range(16)],
                                'wcs', [f'd{h}' for h in (3, 5, 6, 9, 10, 12)])
    # vx is intentionally the wide intrinsic, not the retained XMM helper.
    lines.extend(line.replace('vx(', '_mm512_xor_si512(') for line in code)
    for h, form in zip((3, 5, 6, 9, 10, 12), forms):
        symbols[f'd{h}'] = (form,)*4
    expected = maps.packet_coefficient_forms(coefficients)
    for h in stream.HIGH:
        if symbols[f'd{h}'] != expected[h]:
            raise ArithmeticError(f'wide coefficient d{h} changed its four linear forms')
    if len(broadcasts) != 16 or masked_count != 11 or count != 12:
        raise ArithmeticError('wide coefficient circuit cost unexpectedly changed')
    lines.insert(0, '//16 lane broadcasts +11 masked XORs +12 shared quadratic XORs; '
                    'no128-bit extracts/inserts.')
    lines.extend((
        'const auto cache0=Pruned?_mm512_xor_si512(d0,d8):_mm512_setzero_si512();',
        'const auto cache1=Pruned?_mm512_xor_si512(d1,d9):_mm512_setzero_si512();',
        'const auto cache2=Pruned?_mm512_xor_si512(d2,d10):_mm512_setzero_si512();',
    ))
    return lines


def generate():
    coefficients, expected, digest = stream.prepare()
    stream.verify(coefficients, expected)
    prefix = coefficients_code(coefficients)
    source = [f'''// Generated by further_map_wide_codegen.py; exact retained t64/s16 map.
// Selected map SHA256: {digest}
#pragma once
#include "InnerComposed.h"
#include <array>
namespace spin::research::packet_inner {{
#if defined(__AVX512VBMI__) || (defined(SPIN_PACKET_ENABLE_VBMI) && SPIN_PACKET_ENABLE_VBMI)
namespace further_map_detail {{
template<bool Pruned,bool Incremental,class Emit>
static SPIN_FORCEINLINE void streamHigh(const composed_detail::WordPackets16& state,
const spin::detail::kernel::block* raw,std::size_t packetBase,Emit& emit,__m512i* high){{''']
    source.extend(prefix)
    source.append('if constexpr(Incremental){')
    source.extend(stream.emit_incremental())
    source.append('}else{')
    source.extend(stream.emit_grouped())
    source.append('}\n}')
    source.append('''template<bool Pruned,bool Incremental,class Emit>
static SPIN_FORCEINLINE void streamMoments(const composed_detail::WordPackets16& state,
const spin::detail::kernel::block* raw,std::size_t packetBase,Emit& emit,__m128i* moments){
alignas(64) __m512i high[16];
streamHigh<Pruned,Incremental>(state,raw,packetBase,emit,high);
using feedback_detail::storeLowMoments;''')
    source.extend(f'storeLowMoments<{4*h},{2-h.bit_count()}>(high[{h}],moments);'
                  for h in stream.HIGH)
    source.append('}\n')
    source.append('''template<bool Pruned,bool Incremental,class Emit>
static SPIN_FORCEINLINE void reverse(const spin::detail::kernel::block* input,
std::size_t n,const ComposedWordRow16* rows,Emit& emit){
using namespace composed_detail;
alignas(64) __m128i moments[64],syndrome[16];
alignas(64) __m512i packets[16];
gf::Packed<16> before;
WordPackets16 state;
for(std::size_t epoch=n/64;epoch-- >0;){
const auto* raw=input+64*epoch;
const bool first=epoch+1==n/64;
if(first){
packet_kernel_detail::loadPackets(raw,packets,std::make_index_sequence<16>{});
for(unsigned h=16;h-- >0;)emit(16*epoch+h,packets[h]);
}else{
if(epoch){packWordGroup<0>(state,before);packWordGroup<1>(state,before);}
streamMoments<Pruned,Incremental>(state,raw,16*epoch,emit,moments);
}
if(!epoch)break;
if(first)packetMoments(packets,moments);
Maps<true>::finish(moments,syndrome);
if(first)wordPackets(syndrome,state);
else applyPackedToPackets(before,rows[epoch],syndrome,state);
}
}
} // further_map_detail
#endif

// Same typed setup and descending emitter contract as ComposedWide Stream.
// Only the state-to-packet coefficient boundary changes; setup, update,
// feedback, first/last physical steps and routing remain exact.
template<bool Pruned=false,bool Incremental=false,class Emit>
static SPIN_FORCEINLINE void transposeInnerFurtherWide(
const spin::detail::kernel::block* input,std::size_t n,
PreparedComposedUpdates16::Rows updates,Emit&& emit){
static_assert(packetInnerVbmiCompiled || sizeof(Emit)==0,
"wide packet emission requires a VBMI-enabled translation unit");
if(n%64 || updates.size()!=n/64)
throw std::invalid_argument("wide packet emission length and update count disagree");
if(!n)return;
if(!input)throw std::invalid_argument("wide packet emission input is null");
#if defined(__AVX512VBMI__) || (defined(SPIN_PACKET_ENABLE_VBMI) && SPIN_PACKET_ENABLE_VBMI)
further_map_detail::reverse<Pruned,Incremental>(input,n,updates.data(),emit);
#endif
}

// Retained-harness adapter: Packet remains the unmodified comparison path;
// Stream selects this candidate. Selection is wholly compile-time.
template<ComposedRecipe Recipe,class Emit>
static SPIN_FORCEINLINE void transposeInnerFurtherWideRecipe(
const spin::detail::kernel::block* input,std::size_t n,
PreparedComposedUpdates16::Rows updates,Emit&& emit){
if constexpr(Recipe==ComposedRecipe::Packet)
transposeInnerComposedWide<Recipe>(input,n,updates,emit);
else{
static_assert(Recipe==ComposedRecipe::Stream);
transposeInnerFurtherWide<false,false>(input,n,updates,emit);
}
}

// Native exhaustive state basis against literal physical expansion masks;
// no optimized coefficient circuit or state conversion is used by the oracle.
[[nodiscard]] inline bool furtherMapWideSelfCheck(){
#if defined(__AVX512VBMI__) || (defined(SPIN_PACKET_ENABLE_VBMI) && SPIN_PACKET_ENABLE_VBMI)
using Block=spin::detail::kernel::block;
alignas(64) std::uint64_t stateWords[32]{};
alignas(64) Block raw[64]{};
alignas(64) __m512i actual[16],high[16];
composed_detail::WordPackets16 state;
''')
    source.append('static constexpr std::array<std::uint16_t,64> expansion={'
                  + ','.join(hex(form) for form in expected) + '};')
    source.append('''for(unsigned coordinate=0;coordinate<16;++coordinate){
for(unsigned bit=0;bit<128;++bit){
const auto value=std::uint64_t(1)<<(bit&63);
stateWords[2*coordinate+(bit>>6)]=value;
for(unsigned g=0;g<4;++g)state.v[g]=_mm512_load_si512(stateWords+8*g);
std::size_t next=16;bool ordered=true;
auto emit=[&](std::size_t h,__m512i packet){
if(h>=16 || !next || h!=--next){ordered=false;return;}
actual[h]=packet;
};
further_map_detail::streamHigh<false,false>(state,raw,0,emit,high);
if(!ordered || next)return false;
alignas(64) std::uint64_t got[8];
for(unsigned h=0;h<16;++h){
_mm512_store_si512(got,actual[h]);
for(unsigned lane=0;lane<4;++lane){
const auto wanted=(expansion[4*h+lane]>>coordinate&1)?value:0;
if(got[2*lane]!=(bit<64?wanted:0) || got[2*lane+1]!=(bit>=64?wanted:0))return false;
}
}
for(unsigned h=0;h<16;++h){
if(std::popcount(h)>2)continue;
_mm512_store_si512(got,high[h]);
for(unsigned lane=0;lane<4;++lane){
std::uint64_t wanted=0;
for(unsigned p=0;p<16;++p)if((p&h)==h && (expansion[4*p+lane]>>coordinate&1))wanted^=value;
if(got[2*lane]!=(bit<64?wanted:0) || got[2*lane+1]!=(bit>=64?wanted:0))return false;
}
}
stateWords[2*coordinate+(bit>>6)]=0;
}
}
return true;
#else
return false;
#endif
}
} // spin::research::packet_inner
''')
    return '\n'.join(source)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path)
    parser.add_argument('--probe-output', type=Path,
                        help='Generate an isolated copy of the existing full encoder harness')
    parser.add_argument('--verify-only', action='store_true')
    args = parser.parse_args()
    header = generate()
    if args.output and not args.verify_only:
        args.output.write_text(header, encoding='utf-8', newline='\n')
    elif not args.verify_only:
        print(header)
    if args.probe_output and not args.verify_only:
        original = Path(__file__).with_name('creative_probe.cpp').read_text()
        substitutions = (
            ('#include "InnerComposed.h"', '#include "further_mapWide.h"'),
            ('ip::transposeInnerComposedWide<Mode == 3 ? ip::ComposedRecipe::Packet : ip::ComposedRecipe::Stream>',
             'ip::transposeInnerFurtherWideRecipe<Mode == 3 ? ip::ComposedRecipe::Packet : ip::ComposedRecipe::Stream>'),
            ('if(!ip::composedStateSelfCheck())',
             'if(!ip::composedStateSelfCheck() || !ip::furtherMapWideSelfCheck())'),
        )
        for before, after in substitutions:
            if original.count(before) != 1:
                raise ArithmeticError('retained creative probe interface changed: '+before)
            original = original.replace(before, after)
        args.probe_output.write_text(
            '// Generated isolated harness: creative mode4/6 uses wide emission.\n'+original,
            encoding='utf-8', newline='\n')
    print('Verified all44 coefficient lane forms against the retained basis, '
          'all64-input/16-state packet and moment forms; prefix39 operations.', file=sys.stderr)


if __name__ == '__main__':
    main()
