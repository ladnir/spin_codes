"""Emit the exact S16 A/C candidates defined by packed_mixing/s16_maps.py.

The first sixteen NO_CONSTANT_MAP rows define A. Both feedback choices are
embedded explicitly. Scalar Möbius/basis checks validate the generated XOR
finisher; this generator makes no whole-code distance claim.
"""
from collections import Counter
from hashlib import sha256
from itertools import combinations
import json
from pathlib import Path
import sys

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE/'packed_mixing'))
import s16_maps


def finish_circuit(rows):
    expressions = []
    values = {}
    for row in rows:
        coefficients = [(row >> p) & 1 for p in range(128)]
        for bit in range(7):
            for p in range(128):
                if p & (1 << bit):
                    coefficients[p] ^= coefficients[p ^ (1 << bit)]
        support = {p for p, value in enumerate(coefficients) if value}
        if any(p.bit_count() > 2 for p in support):
            raise ArithmeticError('A16 is not supported by the retained degree-two zeta')
        for p in support:
            values[p] = sum(1 << x for x in range(128) if x & p == p)
        expressions.append(support)
    operations = []
    while True:
        pairs = Counter(pair for expression in expressions for pair in combinations(sorted(expression), 2))
        if not pairs:
            break
        pair, count = min(pairs.items(), key=lambda item: (-item[1], item[0]))
        if count < 2:
            break
        identifier = 128+len(operations)
        operations.append((identifier, *pair))
        values[identifier] = values[pair[0]] ^ values[pair[1]]
        for expression in expressions:
            if set(pair) <= expression:
                expression.difference_update(pair)
                expression.add(identifier)
    for row, expression in zip(rows, expressions):
        actual = 0
        for identifier in expression:
            actual ^= values[identifier]
        if actual != row:
            raise ArithmeticError('generated finish circuit differs from the explicit A row')
    return operations, expressions


def name(identifier):
    return f'z[{identifier}]' if identifier < 128 else f'v{identifier-128}'


def balanced(identifiers):
    if not identifiers:
        return '_mm_setzero_si128()'
    if len(identifiers) == 1:
        return name(identifiers[0])
    middle = len(identifiers)//2
    return f'vx({balanced(identifiers[:middle])},{balanced(identifiers[middle:])})'


def main():
    _, weight5, first = s16_maps.candidate('weight5', 0)
    _, bch16, second = s16_maps.candidate('bch16', 0)
    if first['expansion_rows_hex'] != second['expansion_rows_hex']:
        raise ArithmeticError('feedback variants disagree on A16')
    rows = [int(word, 16) for word in first['expansion_rows_hex']]
    columns = [sum(((row >> p) & 1) << j for j, row in enumerate(rows)) for p in range(128)]
    operations, expressions = finish_circuit(rows)
    print('// Generated by gfni_s16_codegen.py; explicit new S16 construction, not S19 truncation.')
    print('#pragma once\n#include "FusedR4Gfni.h"\nnamespace spin::research::s16 {')
    print('struct Expansion {\nstatic constexpr unsigned T=128,S=16;')
    print('static constexpr std::array<std::uint32_t,128> columns{'+','.join(map(hex, columns))+'};')
    print('static constexpr std::uint64_t expansionRows[16][2]={')
    for row in rows:
        print('{'+f'0x{row & ((1 << 64)-1):016x}ULL,0x{row >> 64:016x}ULL'+'},')
    print('};\nstatic SPIN_FORCEINLINE __m128i vx(__m128i a,__m128i b){return _mm_xor_si128(a,b);}')
    print('static SPIN_FORCEINLINE void finish(const __m128i* z,__m128i* out){')
    for identifier, left, right in operations:
        print(f'const auto {name(identifier)}=vx({name(left)},{name(right)});')
    for j, expression in enumerate(expressions):
        print(f'out[{j}]={balanced(sorted(expression))};')
    print('}\n};')
    for typename, feedback, record in (('Weight5', weight5, first), ('Bch16', bch16, second)):
        canonical = json.dumps({'A': record['expansion_rows_hex'], 'C': feedback}, sort_keys=True, separators=(',', ':')).encode()
        digest = sha256(canonical).hexdigest()
        print(f'struct {typename}:Expansion {{')
        print(f'static constexpr const char* name="{record["feedback"]}";')
        print(f'static constexpr const char* mapSha256="{digest}";')
        print('static constexpr std::array<std::uint32_t,128> feedbackColumns{'+','.join(map(hex, feedback))+'};\n};')
        print(f'{typename}: exact A16/C16, map sha256 {digest}', file=sys.stderr)
    print('}')
    print(f'A16 finisher: {len(operations)} shared XOR nodes; exact 128-coordinate basis validated', file=sys.stderr)


if __name__ == '__main__':
    main()
