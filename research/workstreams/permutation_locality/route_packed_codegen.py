"""Emit an experimental packet-routed scratch layout and its exact outer kernel.

  python -B route_packed_codegen.py --emit header > RoutePacked.h
  python -B route_packed_codegen.py BchCircuit.h --emit outer > RoutePacked.cpp
  python -B route_packed_codegen.py --verify-only

Compile with the retained flags plus -mavx512vbmi. Add the generated-header
directory to the include path. No generated files are written by this script.
The outer uses the existing layout-2 GL32 preparation and tile-5 BCH schedule;
its separately named exports MUST receive this new scratch representation.

For native packet column c, row r, and payload byte b, the new address within
an eight-packet (512-byte) group is 64*(b//2) + 8*c + 2*r + b%2.
Routing does one VBMI permutation and eight qword scatter stores per packet.
Each byte is written exactly once: no OR, read-modify-write, or zeroing pass.
An outer plane needs one load, one VBMI permutation, and one GFNI. Across
eight packets this replaces 24 outer unpack instructions with 16 total VBMI
permutations, but replaces eight full-line stores with 64 partial stores.
This is a cost tradeoff to measure, NOT a predicted speedup or a certificate.
The scratch size, 1028-block tile stride, coefficients, and final output stay
unchanged. The four-block tile padding remains untouched. Stores are cached;
there is deliberately no non-temporal partial-line variant.
"""

import argparse
from pathlib import Path
import subprocess
import sys

sys.dont_write_bytecode = True
import packed_bch_tune_codegen as tune
import outer_layout_codegen


PACK_INDEX = [16 * row + 2 * plane + half
              for plane in range(8) for row in range(4) for half in range(2)]
LOAD_INDEX = [8 * (7 - column) + 2 * row + half
              for row in range(4) for half in range(2) for column in range(8)]


def packed_base(native_block_base):
    """Setup-only address conversion; native bases are block offsets."""
    local = native_block_base % 1028
    if local >= 1024 or local % 4:
        raise ValueError('native base is not an active aligned packet')
    column = (local // 4) % 8
    return 16 * native_block_base - 56 * column


def verify():
    if sorted(PACK_INDEX) != list(range(64)) or sorted(LOAD_INDEX) != list(range(64)):
        raise AssertionError('byte controls are not permutations')
    # All active destinations are disjoint and cover the tile, not its padding.
    for tile in (0, 1, 17):
        addresses = []
        for packet in range(256):
            base = packed_base(1028 * tile + 4 * packet)
            addresses.extend(base + 64 * plane + byte
                             for plane in range(8) for byte in range(8))
        if sorted(addresses) != list(range(16448 * tile, 16448 * tile + 16384)):
            raise AssertionError('route coverage or padding mismatch')
    # Compare every input bit of all eight packets/four row lanes against the
    # RETAINED unpack/GFNI network, not an inverse of our new permutation.
    references = {}
    for column in range(8):
        for bit in range(128):
            words = [0] * 8
            words[column] = 1 << bit
            references[column, bit] = tune.pack128(words)
    for column in range(8):
        for row in range(4):
            for bit in range(128):
                packet = bytearray(64)
                packet[16 * row + bit // 8] = 1 << (bit % 8)
                shuffled = bytes(packet[index] for index in PACK_INDEX)
                scratch = bytearray(512)
                for plane in range(8):
                    base = 64 * plane + 8 * column
                    scratch[base:base + 8] = shuffled[8 * plane:8 * plane + 8]
                for plane in range(8):
                    loaded = scratch[64 * plane:64 * plane + 64]
                    matrix_bytes = bytes(loaded[index] for index in LOAD_INDEX)
                    for output_row in range(4):
                        matrix = int.from_bytes(matrix_bytes[16 * output_row:16 * output_row + 16], 'little')
                        actual = tune.bit_transpose128(matrix, True)
                        expected = references[column, bit][plane] if output_row == row else 0
                        if actual != expected:
                            raise AssertionError((column, row, bit, plane, output_row))
    print('Route packing: all 4096 input-bit bases match retained tile-5 packing; '
          'three complete padded-tile route bijections verified.', file=sys.stderr)


def emit_header():
    packet_control = ','.join(map(str, PACK_INDEX))
    load_control = ','.join(map(str, LOAD_INDEX))
    print(r'''#pragma once
// Generated by route_packed_codegen.py. Experimental scratch representation;
// never pass it to bchPackedCoeff* or native scratch to bchRoutePackedCoeff*.
#include "Spin.h"
#include <immintrin.h>
#include <array>
#include <cstddef>
#include <cstdint>
#include <cstring>
#include <limits>
#include <stdexcept>

#if !defined(__AVX512VBMI__)
#error "RoutePacked requires AVX-512 VBMI in addition to the retained GFNI flags"
#endif

namespace spin::research::route_packed {
namespace detail {
''')
    print(f'alignas(64) static constexpr std::uint8_t packetIndex[64] = {{{packet_control}}};')
    print(f'alignas(64) static constexpr std::uint8_t planeIndex[64] = {{{load_control}}};')
    print(r'''} // namespace detail

// Preparation only: consume the old uint32 block-offset route, producing a
// DIFFERENT uint32 byte-offset route. The caller owns and bounds-checks scratch.
// No padding base, unaligned packet base, or overflowing byte offset is accepted.
inline std::uint32_t packedBaseBytes(std::uint32_t nativeBlockBase) {
    const auto local = nativeBlockBase % 1028U;
    if(local >= 1024U || local % 4U != 0)
        throw std::invalid_argument("route-packed base is not an active packet");
    const auto value = std::uint64_t(nativeBlockBase) * 16 - 56 * ((local / 4) % 8);
    if(value > std::numeric_limits<std::uint32_t>::max() - 455U)
        throw std::overflow_error("route-packed byte offset exceeds uint32");
    return static_cast<std::uint32_t>(value);
}

// packet is passed by value. Its native four-128-bit-lane representation
// remains available to inner feedback. Destination is the packet's converted
// byte base, not a complete 64-byte line. Each scatter writes eight qwords.
static SPIN_FORCEINLINE void storePacket(void* destination, __m512i packet) {
    const auto ordered = _mm512_permutexvar_epi8(
        _mm512_load_si512(detail::packetIndex), packet);
    const auto offsets = _mm512_setr_epi64(0,64,128,192,256,320,384,448);
    _mm512_i64scatter_epi64(destination, offsets, ordered, 1);
}

// PacketInnerKernel emitter. Scratch must have the old padded allocation;
// bases must come from packedBaseBytes, not the native block-offset array.
// A route permutation gives disjoint writes, so scratch need not be cleared.
struct Emitter {
    unsigned char* scratch;
    const std::uint32_t* byteBases;
    SPIN_FORCEINLINE void operator()(std::size_t packet, __m512i value) const {
        storePacket(scratch + byteBases[packet], value);
    }
};

// One 64-byte plane of eight routed packets -> exact packedTunePack5 plane.
// The reversed column order is the matrix-row convention of GFNI, not a
// permutation of the code's eight logical input columns.
static SPIN_FORCEINLINE __m512i loadPlane(const void* source) {
    const auto matrices = _mm512_permutexvar_epi8(
        _mm512_load_si512(detail::planeIndex), _mm512_loadu_si512(source));
    const auto basis = _mm512_set1_epi64(0x0102040810204080ULL);
    return _mm512_gf2p8affine_epi64_epi8(basis, matrices, 0);
}

// Optional native check, active under NDEBUG. Tests the 4096 single-bit inputs
// against the explicit retained layout (not merely a pack/unpack roundtrip),
// checks the intermediate scratch bytes, and checks both 64-byte canaries.
inline bool routePackedSelfCheck() {
    alignas(64) std::array<std::uint8_t,640> guarded;
    alignas(64) std::array<std::uint8_t,64> packet, actual, expected;
    std::array<std::uint8_t,512> expectedScratch;
    auto* scratch = guarded.data() + 64;
    for(unsigned column = 0; column < 8; ++column)
        for(unsigned row = 0; row < 4; ++row)
            for(unsigned bit = 0; bit < 128; ++bit) {
                guarded.fill(0xa5);
                std::memset(scratch, 0, 512);
                packet.fill(0);
                packet[16 * row + bit / 8] = std::uint8_t(1U << (bit % 8));
                storePacket(scratch + 8 * column, _mm512_load_si512(packet.data()));
                expectedScratch.fill(0);
                expectedScratch[64 * (bit / 16) + 8 * column + 2 * row + (bit / 8) % 2]
                    = std::uint8_t(1U << (bit % 8));
                if(std::memcmp(scratch, expectedScratch.data(), 512)) return false;
                for(unsigned byte = 0; byte < 64; ++byte)
                    if(guarded[byte] != 0xa5 || guarded[576 + byte] != 0xa5) return false;
                for(unsigned plane = 0; plane < 8; ++plane) {
                    _mm512_store_si512(actual.data(), loadPlane(scratch + 64 * plane));
                    expected.fill(0);
                    if(plane == bit / 16)
                        expected[16 * row + 8 * ((bit / 8) % 2) + 7 - bit % 8]
                            = std::uint8_t(1U << column);
                    if(actual != expected) return false;
                }
            }
    return true;
}
} // namespace spin::research::route_packed

namespace spin::detail::kernel {
void bchRoutePackedCoeffOriginal(const block*, block*, const std::uint64_t*);
void bchRoutePackedCoeffAligned(const block*, block*, const std::uint64_t*);
void bchRoutePackedCoeffCompact(const block*, block*, const std::uint64_t*);
unsigned routePackedCoeffTileMode();
unsigned routePackedOuterLayoutMode();
} // namespace spin::detail::kernel
''')


def emit_outer(header):
    source = subprocess.run(
        [sys.executable, '-B', str(Path(outer_layout_codegen.__file__).resolve()),
         str(header), '--mode', '2', '--tile-mode', '5'],
        check=True, capture_output=True, text=True)
    if source.stderr:
        print(source.stderr, file=sys.stderr, end='')
    old = '\n'.join(f'auto v{j}=_mm512_loadu_si512(a+4*(8*group+{j}));' for j in range(8))
    old += '\npackedTunePack5(' + ','.join(f'v{j}' for j in range(8)) + ');'
    new = '\n'.join(f'auto v{j}=spin::research::route_packed::loadPlane(a+4*(8*group+{j}));'
                    for j in range(8))
    if source.stdout.count(old) != 3:
        raise RuntimeError('retained preparation changed: expected exactly three pack prefixes')
    result = source.stdout.replace(old, new)
    result = result.replace('bchPackedCoeff', 'bchRoutePackedCoeff')
    result = result.replace('packedCoeffTileMode', 'routePackedCoeffTileMode')
    result = result.replace('outerLayoutMode', 'routePackedOuterLayoutMode')
    result = result.replace('coeff_probe_detail', 'route_coeff_probe_detail')
    print('#include "RoutePacked.h"')
    print(result, end='')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('header', type=Path, nargs='?')
    parser.add_argument('--emit', choices=('header', 'outer'), default='header')
    parser.add_argument('--verify-only', action='store_true')
    args = parser.parse_args()
    if args.emit == 'outer' and not args.verify_only and args.header is None:
        parser.error('BchCircuit.h is required for --emit outer')
    verify()
    if args.verify_only:
        return
    if args.emit == 'header':
        emit_header()
    else:
        emit_outer(args.header)


if __name__ == '__main__':
    main()
